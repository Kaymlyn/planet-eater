    @Test
    @DisplayName("Targeted extraction boosts fraction of target materials")
    void testExtractTargetedBoostsFraction() {
        double ironMass = 1000.0;
        double silicaMass = 3000.0;
        composition.addMaterialAsRawMass(Material.IRON, ironMass);
        composition.addMaterialAsRawMass(Material.SILICA, silicaMass);

        double extractionMass = 200.0;
        double efficiency = 3.0;
        Composition extracted = composition.extract(extractionMass, efficiency, Material.IRON);

        // Extraction formula:
        //   ironFraction = 1000/4000 = 0.25
        //   silicaFraction = 3000/4000 = 0.75
        //   adjustedIron = 0.25 * 3.0 = 0.75
        //   adjustedSilica = 0.75 (not targeted, unchanged)
        //   normalizer = 0.75 + 0.75 = 1.50
        //   ironExtracted = 200 * 0.75 / 1.50 = 100
        //   silicaExtracted = 200 * 0.75 / 1.50 * 0.05 = 5 (untargeted retention = 5%)
        double totalMass = ironMass + silicaMass;
        double ironFraction = ironMass / totalMass;
        double silicaFraction = silicaMass / totalMass;
        double adjustedIron = ironFraction * Math.abs(efficiency);
        double adjustedSilica = silicaFraction;
        double normalizer = adjustedIron + adjustedSilica;
        double expectedIronExtracted = extractionMass * adjustedIron / normalizer;
        double expectedSilicaExtracted = extractionMass * adjustedSilica / normalizer * UNTARGETED_RETENTION;

        assertAll("Targeted extraction shifts mass toward target",
                () -> assertEquals(expectedIronExtracted, extracted.getMass(Material.IRON), TOLERANCE,
                        "Targeted iron extracted must match formula: extractionMass * adjustedFraction / normalizer"),
                () -> assertEquals(expectedSilicaExtracted, extracted.getMass(Material.SILICA), TOLERANCE,
                        "Non-targeted silica retained at 5% of its share")
        );
    }

