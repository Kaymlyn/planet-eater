    @Test
    @DisplayName("Spacecraft velocity changes after burn execution")
    void testPositionIndependentAfterLaunch() {
        // Create and launch spacecraft with a significant burn
        double burnTime = system.getCurrentTime() + 3600.0;
        Itinerary itinerary = new Itinerary(system.getCurrentTime());
        itinerary.addBurn(new ScheduledBurn(
                "departure",
                burnTime,
                new Vector3D(100.0, 0.0, 0.0),
                "Departure burn"
        ));
        itinerary.setDestination(venus);
        itinerary.setFinalState(Spacecraft.SpacecraftState.ORBITING);

        standardShuttle.programItinerary(itinerary);
        standardShuttle.launch(system.getTimeStep());

        // Capture velocity before burn
        Vector3D velocityBeforeBurn = standardShuttle.getVelocity();

        // Advance past burn
        double afterBurnTime = burnTime + 100.0;
        while (system.getCurrentTime() < afterBurnTime) {
            system.stepVerlet();
        }
        system.stepVerlet(); //One step after the burn time

        Vector3D velocityAfterBurn = standardShuttle.getVelocity();

        // The burn should have changed velocity
        assertNotEquals(velocityBeforeBurn, velocityAfterBurn,
                "Velocity should change after burn execution");

        // After enough time with different velocity, positions should diverge
        Vector3D shuttlePos = standardShuttle.getPosition();
        Vector3D platformPos = platform.getPosition();

        // Distance should be non-zero after burn and time passage
        double distance = shuttlePos.subtract(platformPos).magnitude();
        assertTrue(distance > 0.1,
                "Spacecraft should have separated from platform after burn (distance: " + distance + " m)");
    }

