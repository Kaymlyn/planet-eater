    // ==================== DELTA-V CALCULATION TESTS (UNCHANGED) ====================

    @Test
    @DisplayName("Calculate available delta-V")
    void testAvailableDeltaV() {
        double initialMass = standardVehicle.getTotalMass();
        double finalMass = initialMass - standardVehicle.getFuelMass();
        double expected = STANDARD_EXHAUST_VELOCITY * Math.log(initialMass / finalMass);

        assertEquals(expected, standardVehicle.getAvailableDeltaV(), TOLERANCE);
    }

    @Test
    @DisplayName("Delta-V decreases as fuel consumed")
    void testDeltaVDecreasesWithFuel() {
        double initial = standardVehicle.getAvailableDeltaV();

        standardVehicle.consumeFuel(5000.0);
        double half = standardVehicle.getAvailableDeltaV();

        assertTrue(half < initial);
    }

    @Test
    @DisplayName("Zero fuel gives zero delta-V")
    void testZeroFuelZeroDeltaV() {
        standardVehicle.setFuelMass(0.0);
        assertEquals(0.0, standardVehicle.getAvailableDeltaV(), TOLERANCE);
    }

    @Test
    @DisplayName("Calculate fuel required")
    void testFuelRequired() {
        double targetDeltaV = 1000.0;
        double currentMass = standardVehicle.getTotalMass();
        double expected = currentMass - currentMass / Math.exp(targetDeltaV / STANDARD_EXHAUST_VELOCITY);

        assertEquals(expected, standardVehicle.fuelRequired(targetDeltaV), TOLERANCE);
    }

