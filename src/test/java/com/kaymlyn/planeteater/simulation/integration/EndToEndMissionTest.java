    @Test
    @DisplayName("System handles long-duration missions without numerical issues")
    void testLongDurationStability() {
        Spacecraft shuttle = VehicleFactory.createCargoShuttle("Endurance-1", platform);

        double departureTime = system.getCurrentTime() + 86400.0;
        Itinerary route = shuttle.planRoute(mars, false, departureTime,
                TransferPlanner.OptimizationGoal.MINIMUM_DELTAV);

        shuttle.programItinerary(route);
        shuttle.launch(system.getTimeStep());

        double initialEnergy = calculateSystemEnergy();

        // Simulate mission
        int steps = 0;
        int maxSteps = 50000;
        while (!route.isComplete(system.getCurrentTime()) && steps < maxSteps) {
            system.stepVerlet();

            // Check for NaN or infinity
            assertAll("Numerical stability check",
                    () -> assertFalse(Double.isNaN(shuttle.getPosition().getX()), "Position should not be NaN"),
                    () -> assertFalse(Double.isInfinite(shuttle.getVelocity().magnitude()), "Velocity should not be infinite"),
                    () -> assertTrue(shuttle.getFuelMass() >= 0, "Fuel should not go negative")
            );

            steps++;
        }

        double finalEnergy = calculateSystemEnergy();

        // Energy should be roughly conserved (within reasonable tolerance for numerical integration)
        double energyChange = Math.abs(finalEnergy - initialEnergy) / Math.abs(initialEnergy);

        assertTrue(energyChange < 0.1,
                String.format("Energy conservation: change=%.2f%% (should be <10%%)", energyChange * 100.0));

        System.out.println(String.format(
                "Long-duration stability test passed. %d steps simulated. Energy drift: %.4f%%",
                steps, energyChange * 100.0
        ));
    }

