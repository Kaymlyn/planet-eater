    /**
     * Calculate total system energy (kinetic + potential) for validation.
     * This is a simplified calculation for testing purposes.
     */
    private double calculateSystemEnergy() {
        double totalEnergy = 0.0;

        // Add kinetic energy of orbiting bodies
        for (var orbiter : system.getOrbiters().values()) {
            double kineticEnergy = 0.5 * orbiter.getMass() *
                    Math.pow(orbiter.getVelocity().magnitude(), 2);
            totalEnergy += kineticEnergy;
        }

        return totalEnergy;
    }
