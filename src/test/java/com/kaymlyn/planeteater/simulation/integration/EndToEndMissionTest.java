    @Test
    @DisplayName("Complete Earth to Mars mission")
    void testEarthToMarsMission() {
        // Step 1: Create spacecraft at platform
        Spacecraft shuttle = VehicleFactory.createCargoShuttle("Explorer-1", platform);

        assertAll("Initial spacecraft state",
                () -> assertEquals(Spacecraft.SpacecraftState.DOCKED, shuttle.getState()),
                () -> assertEquals(platform, shuttle.getOrbiting()),
                () -> assertTrue(shuttle.getFuelMass() > 0, "Should have fuel")
        );

        // Step 2: Plan route to Mars
        double departureTime = system.getCurrentTime() + 86400.0; // Depart in 1 day
        Itinerary route = shuttle.planRoute(
                mars,
                false,  // Orbit Mars, don't land
                departureTime,
                TransferPlanner.OptimizationGoal.MINIMUM_DELTAV
        );

        assertNotNull(route, "Should generate a route to Mars");
        assertTrue(route.isFeasible(), "Route should be feasible");
        assertTrue(route.getBurns().size() >= 2, "Should have at least departure and arrival burns");

        // Step 3: Program itinerary and launch
        shuttle.programItinerary(route);
        double initialFuel = shuttle.getFuelMass();
        boolean launched = shuttle.launch(system.getTimeStep());

        assertAll("Launch sequence",
                () -> assertTrue(launched, "Launch should succeed"),
                () -> assertEquals(Spacecraft.SpacecraftState.TRAVELING, shuttle.getState()),
                () -> assertFalse(platform.getHanger().containsKey("Explorer-1"), "Should leave platform")
        );

        // Step 4: Simulate mission
        int maxSteps = 50000; // Prevent infinite loops (about 5.7 years at 1 hour steps)
        int steps = 0;

        while (!route.isComplete(system.getCurrentTime()) && steps < maxSteps) {
            system.stepVerlet();
            steps++;
        }

        assertTrue(steps < maxSteps, "Mission should complete before timeout");

        // Step 5: Validate arrival
        double distanceToMars = shuttle.getPosition().subtract(mars.getPosition()).magnitude();
        double marsOrbitRadius = mars.getStandardOrbitalRadius();

        assertAll("Mission completion",
                () -> assertTrue(route.isComplete(system.getCurrentTime()), "Itinerary should be complete"),
                () -> assertEquals(Spacecraft.SpacecraftState.ORBITING, shuttle.getState()),
                () -> assertEquals(mars, shuttle.getOrbiting()),
                () -> assertTrue(distanceToMars < marsOrbitRadius * 2.0,
                        String.format("Distance to Mars %.0f km should be within tolerance", distanceToMars / 1000.0))
        );

        // Step 6: Verify fuel consumption
        double fuelConsumed = initialFuel - shuttle.getFuelMass();
        double expectedDeltaV = route.getTotalDeltaV();

        assertAll("Fuel consumption",
                () -> assertTrue(fuelConsumed > 0, "Should have consumed fuel"),
                () -> assertTrue(fuelConsumed < initialFuel, "Should have fuel remaining"),
                () -> assertTrue(expectedDeltaV > 0, "Should have required delta-V")
        );

        System.out.println(String.format(
                "Mission completed in %d steps (%.1f days). Fuel consumed: %.1f kg. Final distance to Mars: %.0f km",
                steps, steps * TIME_STEP / 86400.0, fuelConsumed, distanceToMars / 1000.0
        ));
    }

