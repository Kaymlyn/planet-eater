package com.kaymlyn.planeteater.simulation.physics;

import com.kaymlyn.planeteater.simulation.celestial.Star;
import com.kaymlyn.planeteater.simulation.celestial.CelestialBodyFactory;
import com.kaymlyn.planeteater.simulation.celestial.OrbitalSystem;
import com.kaymlyn.planeteater.simulation.physics.Orbit;
import com.kaymlyn.planeteater.simulation.physics.OrbitalState;
import com.kaymlyn.planeteater.simulation.physics.PhysicsConstants;
import com.kaymlyn.planeteater.simulation.physics.Vector3D;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.DisplayName;

import static org.junit.jupiter.api.Assertions.*;



/**
 * Unit test to verify round-trip consistency of Orbit calculations.
 *
 * Tests that: position → calculateOrbit → calculateOrbitalState → position
 * produces the same position within numerical precision.
 *
 * This verifies the fix for the coordinate system mismatch between
 * calculateOrbit (which now projects to 2D before measuring angles) and
 * calculateOrbitalState (which interprets angles as 2D orbital plane measurements).
 *
 * Generated by Claude (Sonnet 4.5)
 */
public class OrbitRoundTripTest {

    private static Star sun;
    private static CelestialBodyFactory factory;
    private static OrbitalSystem system;

    private static final double POSITION_TOLERANCE = 1000.0; // 1 km tolerance
    private static final double VELOCITY_TOLERANCE = 10.0;   // 10 m/s tolerance

    @BeforeAll
    static void setup() {
        sun = CelestialBodyFactory.createMainSequenceStar("TestStar", 1.0);
        factory = new CelestialBodyFactory(sun, 3600.0);
        system = factory.getSystem();
    }

    @Test
    @DisplayName("Simple circular orbit at 1 AU on ecliptic")
    void testCircularOrbitEcliptic() {
        Vector3D position = new Vector3D(PhysicsConstants.AU, 0, 0);
        Vector3D velocity = new Vector3D(0, 29780, 0);

        testRoundTrip(position, velocity, "Circular ecliptic");
    }

    @Test
    @DisplayName("Circular orbit at periapsis (x-axis)")
    void testCircularAtPeriapsis() {
        Vector3D position = new Vector3D(PhysicsConstants.AU, 0, 0);
        double orbitalVel = Math.sqrt(sun.getGravitationalParameter() / PhysicsConstants.AU);
        Vector3D velocity = new Vector3D(0, orbitalVel, 0);

        testRoundTrip(position, velocity, "Periapsis");
    }

    @Test
    @DisplayName("Circular orbit at 90 degrees")
    void testCircularAt90Degrees() {
        Vector3D position = new Vector3D(0, PhysicsConstants.AU, 0);
        double orbitalVel = Math.sqrt(sun.getGravitationalParameter() / PhysicsConstants.AU);
        Vector3D velocity = new Vector3D(-orbitalVel, 0, 0);

        testRoundTrip(position, velocity, "90 degrees");
    }

    @Test
    @DisplayName("Elliptical orbit at periapsis")
    void testEllipticalAtPeriapsis() {
        double periapsis = 0.5 * PhysicsConstants.AU;
        Vector3D position = new Vector3D(periapsis, 0, 0);

        // Velocity for e=0.5 orbit
        double semiMajorAxis = PhysicsConstants.AU;
        double vPeriapsis = Math.sqrt(sun.getGravitationalParameter() *
                (2.0 / periapsis - 1.0 / semiMajorAxis));
        Vector3D velocity = new Vector3D(0, vPeriapsis, 0);

        testRoundTrip(position, velocity, "Elliptical periapsis");
    }

    @Test
    @DisplayName("Inclined orbit (30 degrees)")
    void testInclinedOrbit() {
        double inclination = Math.toRadians(30);
        double radius = PhysicsConstants.AU;

        // Position on inclined orbit
        Vector3D position = new Vector3D(
                radius * Math.cos(inclination),
                0,
                radius * Math.sin(inclination)
        );

        // Circular orbital velocity
        double vMag = Math.sqrt(sun.getGravitationalParameter() / radius);
        Vector3D velocity = new Vector3D(0, vMag, 0);

        testRoundTrip(position, velocity, "Inclined 30°");
    }

    @Test
    @DisplayName("Generic 3D elliptical orbit")
    void test3DEllipticalOrbit() {
        // This is the failing case from the original output
        Vector3D position = new Vector3D(
                1.496e11,  // ~1 AU
                4.488e10,  // ~0.3 AU
                2.992e10   // ~0.2 AU
        );
        Vector3D velocity = new Vector3D(-15000, 25000, 5000);

        testRoundTripWithDebug(position, velocity, "3D elliptical");
    }

    /**
     * Helper method to test round-trip consistency
     */
    private void testRoundTrip(Vector3D originalPos, Vector3D originalVel, String testName) {
        // Calculate orbit from position/velocity
        Orbit orbit = Orbit.calculateOrbit(sun, originalPos, originalVel,system.getCurrentTime());

        // Calculate state from orbit
        OrbitalState state = orbit.calculateOrbitalState();

        // Check position
        double posError = state.position().subtract(originalPos).magnitude();
        double velError = state.velocity().subtract(originalVel).magnitude();

        System.out.printf("%s: pos_err=%.1fm, vel_err=%.1fm/s\n",
                testName, posError, velError);

        assertTrue(posError < POSITION_TOLERANCE,
                String.format("%s: Position error %.1f m exceeds tolerance %.1f m",
                        testName, posError, POSITION_TOLERANCE));

        assertTrue(velError < VELOCITY_TOLERANCE,
                String.format("%s: Velocity error %.1f m/s exceeds tolerance %.1f m/s",
                        testName, velError, VELOCITY_TOLERANCE));
    }

    /**
     * Helper with detailed debugging output
     */
    private void testRoundTripWithDebug(Vector3D originalPos, Vector3D originalVel, String testName) {
        System.out.println("\n=== DEBUGGING: " + testName + " ===");
        System.out.println("Original position: " + originalPos);
        System.out.println("Original velocity: " + originalVel);

        // Calculate orbit
        Orbit orbit = Orbit.calculateOrbit(sun, originalPos, originalVel, system.getCurrentTime());

        System.out.println("\nOrbit elements:");
        System.out.printf("  a = %.3e m\n", orbit.semiMajorAxis());
        System.out.printf("  e = %.6f\n", orbit.eccentricity());
        System.out.printf("  i = %.3f°\n", Math.toDegrees(orbit.inclination()));
        System.out.printf("  Ω = %.3f°\n", Math.toDegrees(orbit.ascendingNode()));
        System.out.printf("  ω = %.3f°\n", Math.toDegrees(orbit.periapsis()));
        System.out.printf("  ν = %.3f°\n", Math.toDegrees(orbit.trueAnomaly()));

        // Project to 2D orbital plane manually to verify
        Vector3D pos2D = originalPos.rotateInto2spaceFrom3space(
                orbit.ascendingNode(),
                orbit.inclination(),
                orbit.periapsis()
        );
        System.out.println("\nPosition in 2D orbital plane: " + pos2D);

        // What angle does this give?
        double manualAngle = Math.atan2(pos2D.getY(), pos2D.getX());
        System.out.printf("Manual 2D angle: %.3f° (%.3f rad)\n",
                Math.toDegrees(manualAngle), manualAngle);
        System.out.printf("Orbit true anomaly: %.3f° (%.3f rad)\n",
                Math.toDegrees(orbit.trueAnomaly()), orbit.trueAnomaly());

        // Calculate state
        OrbitalState state = orbit.calculateOrbitalState();

        System.out.println("\nRecovered position: " + state.position());
        System.out.println("Recovered velocity: " + state.velocity());

        // Errors
        double posError = state.position().subtract(originalPos).magnitude();
        double velError = state.velocity().subtract(originalVel).magnitude();

        System.out.printf("\nPosition error: %.1f m\n", posError);
        System.out.printf("Velocity error: %.1f m/s\n", velError);

        // Also check what happens when we reconstruct from 2D
        double r = pos2D.magnitude();
        Vector3D reconstructed2D = new Vector3D(
                r * Math.cos(orbit.trueAnomaly()),
                r * Math.sin(orbit.trueAnomaly()),
                0
        );
        System.out.println("\nReconstructed 2D position: " + reconstructed2D);
        System.out.println("Original 2D position: " + pos2D);

        Vector3D reconstructed3D = reconstructed2D.rotateInto3spaceFrom2space(
                orbit.ascendingNode(),
                orbit.inclination(),
                orbit.periapsis()
        );
        System.out.println("Reconstructed 3D position: " + reconstructed3D);

        double reconstructionError = reconstructed3D.subtract(originalPos).magnitude();
        System.out.printf("Direct reconstruction error: %.1f m\n", reconstructionError);

        // Fail with message
        assertTrue(posError < POSITION_TOLERANCE,
                String.format("%s: Position error %.1f m exceeds tolerance %.1f m\n" +
                                "See debug output above",
                        testName, posError, POSITION_TOLERANCE));
    }
}

