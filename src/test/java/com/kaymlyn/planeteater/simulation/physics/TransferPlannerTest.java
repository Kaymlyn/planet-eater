    @Test
    @DisplayName("Hohmann transfer delta-V matches analytical formula")
    void testHohmannDeltaVAccuracy() {
        Orbit earthOrbit = earth.snapshotOrbit();
        Orbit marsOrbit = mars.snapshotOrbit();
        double departureTime = system.getCurrentTime() + 3600.0;

        Itinerary itinerary = TransferPlanner.buildHohmannTransfer(
                shuttle, earthOrbit, marsOrbit, earth, mars, false, departureTime
        );

        // Calculate expected delta-V using Hohmann formula
        double mu = factory.getCentralStar().getGravitationalParameter();
        double r1 = earthOrbit.semiMajorAxis();
        double r2 = marsOrbit.semiMajorAxis();
        double aTransfer = (r1 + r2) / 2.0;

        // Departure delta-V
        double vCircular1 = Math.sqrt(mu / r1);
        double vPeriapsis = Math.sqrt(mu * (2.0 / r1 - 1.0 / aTransfer));
        double expectedDeltaV1 = Math.abs(vPeriapsis - vCircular1);

        // Arrival delta-V
        double vCircular2 = Math.sqrt(mu / r2);
        double vApoapsis = Math.sqrt(mu * (2.0 / r2 - 1.0 / aTransfer));
        double expectedDeltaV2 = Math.abs(vCircular2 - vApoapsis);

        double expectedTotalDeltaV = expectedDeltaV1 + expectedDeltaV2;
        double actualTotalDeltaV = itinerary.getTotalDeltaV();

        assertEquals(expectedTotalDeltaV, actualTotalDeltaV, DELTA_V_TOLERANCE,
                "Total delta-V should match Hohmann formula");
    }

