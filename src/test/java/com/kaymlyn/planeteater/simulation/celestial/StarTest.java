package com.kaymlyn.planeteater.simulation.celestial;

import com.kaymlyn.planeteater.simulation.physics.PhysicsConstants;
import com.kaymlyn.planeteater.simulation.resources.Material;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Comprehensive test suite for Star.
 *
 * Tests cover:
 * - Construction and identity
 * - Mass conservation across totalComposition and atmosphereComposition
 * - Mass-radius relationship for main sequence stars
 * - Gravitational parameter
 * - Luminosity scaling
 * - Temperature and spectral classification
 * - Atmosphere seeding and extraction
 * - transferToAtmosphere
 *
 * Mass accounting:
 *   initialize() transfers ATMOSPHERE_SEED_FRACTION (1%) of each gas material
 *   from totalComposition into atmosphereComposition. getMass() reads only
 *   totalComposition. Total conserved mass = getMass() + atmosphereComposition mass.
 *
 * All scaling assertions derive expected values from getMass(), not from the ideal
 * construction mass, because getMass() is what all Star methods use internally.
 * After initialization getMass() is slightly below the construction mass by exactly
 * the seeded atmosphere amount (~1% of gas mass, ~0.99% of total).
 *
 * Generated by Claude (Sonnet 4.5)
 */
@DisplayName("Star Tests")
public class StarTest {

    private static final double SOLAR_RADIUS_M           = 6.96e8;
    private static final double SOLAR_TEMP_K             = 5778.0;
    private static final double ATMOSPHERE_SEED_FRACTION = 0.01;

    // Tolerances
    private static final double RELATIVE_TOLERANCE = 1e-3;  // 0.01%
    private static final double MASS_TOLERANCE_KG  = 1e20;  // absolute, kg

    private Star solarMassStar;

    @BeforeEach
    void setUp() {
        solarMassStar = CelestialBodyFactory.createMainSequenceStar("Sol", 1.0);
    }

    // ==================== CONSTRUCTION AND IDENTITY ====================

    @Test
    @DisplayName("getId: returns the id supplied at construction")
    void testIdMatchesConstructionParameter() {
        assertEquals("Sol", solarMassStar.getId(),
                "Star id must match the string passed to createMainSequenceStar");
    }

    @Test
    @DisplayName("getPosition: star is fixed at the coordinate origin")
    void testStarPositionIsOrigin() {
        assertAll("star position is origin",
                () -> assertEquals(0.0, solarMassStar.getPosition().getX(), 1.0,
                        "Star X must be zero"),
                () -> assertEquals(0.0, solarMassStar.getPosition().getY(), 1.0,
                        "Star Y must be zero"),
                () -> assertEquals(0.0, solarMassStar.getPosition().getZ(), 1.0,
                        "Star Z must be zero")
        );
    }

    // ==================== MASS CONSERVATION ====================

    @Test
    @DisplayName("getMass + atmosphere: total conserved mass equals construction mass")
    void testTotalSystemMassConservedAfterInitialization() {
        double expectedTotalMass = PhysicsConstants.SOLAR_MASS;
        double actualTotalMass = solarMassStar.getMass()
                + solarMassStar.getAtmosphereComposition().getTotalMass();

        assertEquals(expectedTotalMass, actualTotalMass, MASS_TOLERANCE_KG,
                "getMass() + atmosphere pool must equal construction mass after seeding");
    }

    @Test
    @DisplayName("getMass: reduced by seeded atmosphere after initialization")
    void testGetMassIsReducedByAtmosphereSeed() {
        double constructionMass = PhysicsConstants.SOLAR_MASS;

        assertTrue(solarMassStar.getMass() < constructionMass,
                "getMass() must be less than construction mass after atmosphere seeding");
        assertTrue(solarMassStar.getMass() > constructionMass * 0.98,
                "getMass() must be within 2% of construction mass (seed is 1% of gas mass)");
    }

    @Test
    @DisplayName("getMass: 0.5 solar mass star total mass scales correctly")
    void testMassScalesWithSolarMassParameter() {
        Star halfMassStar = CelestialBodyFactory.createMainSequenceStar("HalfStar", 0.5);
        double halfMassTotal = halfMassStar.getMass()
                + halfMassStar.getAtmosphereComposition().getTotalMass();
        double solarMassTotal = solarMassStar.getMass()
                + solarMassStar.getAtmosphereComposition().getTotalMass();

        assertEquals(0.5, halfMassTotal / solarMassTotal, RELATIVE_TOLERANCE,
                "A 0.5 solar mass star must have exactly half the total mass");
    }

    // ==================== COMPOSITION FRACTIONS ====================

    @Test
    @DisplayName("composition: hydrogen 73% of total construction mass across both pools")
    void testHydrogenFractionIs73Percent() {
        double expectedHydrogenMass = 1.0 * PhysicsConstants.SOLAR_MASS * 0.73;
        double actualHydrogenMass =
                solarMassStar.getTotalComposition().getMass(Material.HYDROGEN)
                        + solarMassStar.getAtmosphereComposition().getMass(Material.HYDROGEN);

        assertEquals(expectedHydrogenMass, actualHydrogenMass, MASS_TOLERANCE_KG,
                "Hydrogen must be 73% of total construction mass across both compositions");
    }

    @Test
    @DisplayName("composition: helium 25% of total construction mass across both pools")
    void testHeliumFractionIs25Percent() {
        double expectedHeliumMass = PhysicsConstants.SOLAR_MASS * 0.25;
        double actualHeliumMass =
                solarMassStar.getTotalComposition().getMass(Material.HELIUM)
                        + solarMassStar.getAtmosphereComposition().getMass(Material.HELIUM);

        assertEquals(expectedHeliumMass, actualHeliumMass, MASS_TOLERANCE_KG,
                "Helium must be 25% of total construction mass across both compositions");
    }

    // ==================== MASS-RADIUS RELATIONSHIP ====================

    @Test
    @DisplayName("getRadius: derives from M^0.57 scaling using actual getMass()")
    void testSolarMassStarRadiusDerivedFromActualMass() {
        // getMass() is slightly below construction mass after seeding.
        // The method uses getMass()/SOLAR_MASS as the ratio, so derive expected the same way.
        double massRatio = solarMassStar.getMass() / PhysicsConstants.SOLAR_MASS;
        double expectedRadius = SOLAR_RADIUS_M * Math.pow(massRatio, 0.57);

        assertEquals(expectedRadius, solarMassStar.getRadius(), expectedRadius * RELATIVE_TOLERANCE,
                "Radius must match R_sun * (getMass()/M_sun)^0.57 for a near-solar-mass star");
    }

    @Test
    @DisplayName("getRadius: sub-solar mass star follows M^0.8 scaling")
    void testSubSolarMassRadiusScalingExponent() {
        Star halfMassStar = CelestialBodyFactory.createMainSequenceStar("HalfStar", 0.5);
        double massRatio = halfMassStar.getMass() / PhysicsConstants.SOLAR_MASS;
        double expectedRadius = SOLAR_RADIUS_M * Math.pow(massRatio, 0.8);

        assertEquals(expectedRadius, halfMassStar.getRadius(), expectedRadius * RELATIVE_TOLERANCE,
                "Sub-solar mass star radius must follow R_sun * (getMass()/M_sun)^0.8");
    }

    @Test
    @DisplayName("getRadius: super-solar mass star follows M^0.57 scaling")
    void testSuperSolarMassRadiusScalingExponent() {
        Star doubleMassStar = CelestialBodyFactory.createMainSequenceStar("DoubleStar", 2.0);
        double massRatio = doubleMassStar.getMass() / PhysicsConstants.SOLAR_MASS;
        double expectedRadius = SOLAR_RADIUS_M * Math.pow(massRatio, 0.57);

        assertEquals(expectedRadius, doubleMassStar.getRadius(), expectedRadius * RELATIVE_TOLERANCE,
                "Super-solar mass star radius must follow R_sun * (getMass()/M_sun)^0.57");
    }

    // ==================== GRAVITATIONAL PARAMETER ====================

    @Test
    @DisplayName("getGravitationalParameter: equals G * getMass()")
    void testGravitationalParameterEqualsGTimesMass() {
        double expectedMu = PhysicsConstants.G * solarMassStar.getMass();

        assertEquals(expectedMu, solarMassStar.getGravitationalParameter(),
                expectedMu * RELATIVE_TOLERANCE,
                "Gravitational parameter must equal G * getMass()");
    }

    // ==================== LUMINOSITY ====================

    @Test
    @DisplayName("getLuminosity: equals (getMass()/M_sun)^3.5")
    void testLuminosityFormula() {
        double massRatio = solarMassStar.getMass() / PhysicsConstants.SOLAR_MASS;
        double expectedLuminosity = Math.pow(massRatio, 3.5);

        assertEquals(expectedLuminosity, solarMassStar.getLuminosity(), RELATIVE_TOLERANCE,
                "Luminosity must equal (getMass()/M_sun)^3.5");
    }

    @Test
    @DisplayName("getLuminosity: scales consistently between 1x and 2x solar mass")
    void testLuminosityScalingExponent() {
        Star doubleMassStar = CelestialBodyFactory.createMainSequenceStar("DoubleStar", 2.0);
        double massRatio = doubleMassStar.getMass() / PhysicsConstants.SOLAR_MASS;
        double expectedLuminosity = Math.pow(massRatio, 3.5);

        assertEquals(expectedLuminosity, doubleMassStar.getLuminosity(),
                expectedLuminosity * RELATIVE_TOLERANCE,
                "Luminosity of a 2 solar mass star must equal (getMass()/M_sun)^3.5");
    }

    // ==================== TEMPERATURE AND SPECTRAL CLASS ====================

    @Test
    @DisplayName("calculateMainSequenceTemperature: 1 solar mass star is within 1% of 5778 K")
    void testSolarMassStarTemperatureNearSolarValue() {
        double temperature = solarMassStar.calculateMainSequenceTemperature();

        assertEquals(SOLAR_TEMP_K, temperature, SOLAR_TEMP_K * 0.01,
                "A 1 solar mass star must have a temperature within 1% of 5778 K");
    }

    @Test
    @DisplayName("getSpectralClass: 1 solar mass star is class G")
    void testSolarMassStarIsClassG() {
        assertEquals("G", solarMassStar.getSpectralClass(),
                "A 1 solar mass star at ~5778 K must be spectral class G");
    }

    @Test
    @DisplayName("getSpectralClass: 10 solar mass star is class O or B")
    void testHighMassStarHasHotSpectralClass() {
        Star hotStar = CelestialBodyFactory.createMainSequenceStar("HotStar", 10.0);
        String spectralClass = hotStar.getSpectralClass();

        assertTrue(spectralClass.equals("O") || spectralClass.equals("B"),
                "A 10 solar mass star must be spectral class O or B, was: " + spectralClass);
    }

    // ==================== ATMOSPHERE AND EXTRACTION ====================

    @Test
    @DisplayName("atmosphere: hydrogen is present in pool after initialization")
    void testHydrogenPresentInAtmosphereAfterInit() {
        assertTrue(solarMassStar.hasExtractableMaterial(Material.HYDROGEN),
                "Hydrogen must be in the atmosphere pool after initialize()");
    }

    @Test
    @DisplayName("atmosphere: seeded mass equals 1% of gas construction mass")
    void testAtmosphereSeedMassIsCorrectFraction() {
        // Gas materials seeded at 1%: H (73%), He (25%), O_gas (1%) of SOLAR_MASS.
        double constructionMass   = PhysicsConstants.SOLAR_MASS;
        double expectedAtmosphere =
                (constructionMass * 0.73 + constructionMass * 0.25 + constructionMass * 0.01)
                        * ATMOSPHERE_SEED_FRACTION;

        double actualAtmosphere = solarMassStar.getAtmosphereComposition().getTotalMass();

        assertEquals(expectedAtmosphere, actualAtmosphere, MASS_TOLERANCE_KG,
                "Atmosphere pool must contain 1% of total gas construction mass");
    }

    @Test
    @DisplayName("extractStellarMaterial: returns positive mass when material is available")
    void testExtractionReturnsPositiveMass() {
        double extracted = solarMassStar.extractStellarMaterial(
                Material.HYDROGEN, 1e6, 1e4, 1e3);

        assertTrue(extracted > 0.0,
                "Extraction must return a positive mass when hydrogen is available");
    }

    @Test
    @DisplayName("extractStellarMaterial: extracted mass does not exceed rate * duration")
    void testExtractionRespectsRateLimit() {
        double extractionRate = 1e4;
        double duration       = 1e3;
        double rateLimitedMax = extractionRate * duration;

        double extracted = solarMassStar.extractStellarMaterial(
                Material.HYDROGEN, 1e30, extractionRate, duration);

        assertTrue(extracted <= rateLimitedMax + 1.0,
                "Extracted mass must not exceed extractionRate * duration = " + rateLimitedMax);
    }

    @Test
    @DisplayName("extractStellarMaterial: atmosphere pool decreases by extracted amount")
    void testExtractionReducesAtmospherePool() {
        double poolBefore = solarMassStar.getAtmosphereComposition().getMass(Material.HYDROGEN);
        double extracted  = solarMassStar.extractStellarMaterial(
                Material.HYDROGEN, 1e6, 1e4, 1e3);
        double poolAfter  = solarMassStar.getAtmosphereComposition().getMass(Material.HYDROGEN);

        assertEquals(poolBefore - extracted, poolAfter, 1.0,
                "Atmosphere pool must decrease by exactly the extracted amount");
    }

    @Test
    @DisplayName("transferToAtmosphere: moves mass from body composition to atmosphere pool")
    void testTransferToAtmosphereMovesMass() {
        double bodyMassBefore = solarMassStar.getMass();
        double poolBefore     = solarMassStar.getAtmosphereComposition().getMass(Material.HYDROGEN);
        double transferAmount = 1e20;  // kg - large but well within available hydrogen

        double transferred = solarMassStar.transferToAtmosphere(Material.HYDROGEN, transferAmount);

        assertAll("transferToAtmosphere accounting",
                () -> assertEquals(transferAmount, transferred,
                        transferAmount * RELATIVE_TOLERANCE,
                        "Returned amount must equal requested amount when sufficient stock exists"),
                () -> assertEquals(bodyMassBefore - transferred, solarMassStar.getMass(),
                        bodyMassBefore * RELATIVE_TOLERANCE,
                        "Body mass must decrease by transferred amount"),
                () -> assertEquals(poolBefore + transferred,
                        solarMassStar.getAtmosphereComposition().getMass(Material.HYDROGEN),
                        transferred * RELATIVE_TOLERANCE,
                        "Atmosphere pool must increase by transferred amount")
        );
    }
}