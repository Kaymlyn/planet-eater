    /**
     * Builds a minimal probe spacecraft docked at the factory's CentralMind
     * for use in docking tests. Uses factory.createCentralMind() as shipyard
     * so the Spacecraft constructor receives a valid Orbiter.
     */
    private Spacecraft buildMinimalSpacecraft(String id) {
        Composition construction = new Composition();
        construction.addMaterialAsRawMass(Material.ALUMINUM, 100.0);

        // Use a new CentralMind as shipyard so the Spacecraft constructor receives a valid Orbiter
        com.kaymlyn.planeteater.simulation.vehicles.CentralMind platform =
                factory.createCentralMind(PhysicsConstants.AU * 2.0);

        Spacecraft craft = new Spacecraft(
                id,
                construction,
                100.0,   // fuel mass kg
                1.0,     // cargo capacity m^3
                2200.0,  // exhaust velocity m/s
                false,
                0,
                0,
                platform
        );
        platform.dock(craft);
        return craft;
    }
