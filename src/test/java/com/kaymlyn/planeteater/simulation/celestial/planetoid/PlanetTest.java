    @Test
    @DisplayName("Hill sphere radius satisfies r_Hill = d * (m / (3 * M))^(1/3)")
    void testHillSphereFormula() {
        // Law: Hill sphere approximation for secondary body in circular orbit
        // r_Hill = semi-major axis * (mass / (3 * parent_mass))^(1/3)
        double distanceToParent = earthLikePlanet.getPosition()
                .distanceTo(star.getPosition());
        double expectedHillRadius = distanceToParent
                * Math.pow(earthLikePlanet.getMass() / (3.0 * star.getMass()), 1.0 / 3.0);

        assertEquals(expectedHillRadius, earthLikePlanet.calculateHillSphereRadius(), PHYSICS_TOLERANCE,
                "Hill sphere must satisfy r_Hill = d * (m/3M)^(1/3)");
    }

