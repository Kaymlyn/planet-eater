    /**
     * Solve for a two-burn transfer between two arbitrary points on two orbits
     *
     * @param departurePoint Position on initial orbit where first burn occurs
     * @param initialOrbit   Orbital elements of starting orbit
     * @param arrivalPoint   Position on target orbit where second burn occurs
     * @param targetOrbit    Orbital elements of final orbit
     * @param centerBody     Mass of central body (kg)
     * @return Complete two-burn transfer solution
     */
    public static TwoBurnSolution solveTwoBurnTransfer(Vector3D departurePoint,
                                                       Orbit initialOrbit,
                                                       Vector3D arrivalPoint,
                                                       Orbit targetOrbit,
                                                       Gravitational centerBody) {

        // Verify departure point is on initial orbit
        if (!isPointOnOrbit(departurePoint, initialOrbit, 1000.0)) {
            return createInfeasibleSolution(
                    "Departure point is not on initial orbit",
                    departurePoint, arrivalPoint, initialOrbit, targetOrbit
            );
        }

        // Verify arrival point is on target orbit
        if (!isPointOnOrbit(arrivalPoint, targetOrbit, 1000.0)) {
            return createInfeasibleSolution(
                    "Arrival point is not on target orbit",
                    departurePoint, arrivalPoint, initialOrbit, targetOrbit
            );
        }

        // Calculate velocity on initial orbit at departure point
        Vector3D v1_initial = OrbitFromStateVectors.calculateVelocityVector(
                departurePoint, initialOrbit, centerBody
        );

        // Calculate velocity on target orbit at arrival point
        Vector3D v2_target = OrbitFromStateVectors.calculateVelocityVector(
                arrivalPoint, targetOrbit, centerBody
        );

        // Create transfer orbit passing through both points
        TransferOrbitSolution transferSolution = solveTransferOrbit(
                departurePoint, arrivalPoint, centerBody
        );

        if (!transferSolution.feasible) {
            return createInfeasibleSolution(
                    transferSolution.reason,
                    departurePoint, arrivalPoint, initialOrbit, targetOrbit
            );
        }

        Orbit transferOrbit = transferSolution.orbit;
        double transferTime = transferSolution.transferTime;

        // Calculate velocity on transfer orbit at departure
        Vector3D v1_transfer = OrbitFromStateVectors.calculateVelocityVector(
                departurePoint, transferOrbit, centerBody
        );

        // Calculate velocity on transfer orbit at arrival
        Vector3D v2_transfer = OrbitFromStateVectors.calculateVelocityVector(
                arrivalPoint, transferOrbit, centerBody
        );

        // Calculate delta-v for each burn
        Vector3D deltaV1 = v1_transfer.subtract(v1_initial);
        Vector3D deltaV2 = v2_target.subtract(v2_transfer);

        double totalDeltaV = deltaV1.magnitude() + deltaV2.magnitude();

        return new TwoBurnSolution(
                departurePoint, arrivalPoint,
                initialOrbit, transferOrbit, targetOrbit,
                v1_initial, deltaV1, v1_transfer,
                v2_transfer, deltaV2, v2_target,
                transferTime, totalDeltaV,
                true, null
        );
    }

