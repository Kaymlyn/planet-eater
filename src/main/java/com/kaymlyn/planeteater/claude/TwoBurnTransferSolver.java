    /**
     * Solve for the transfer orbit that connects two points
     * Uses Lambert's problem solution
     */
    private static TransferOrbitSolution solveTransferOrbit(Vector3D r1, Vector3D r2,
                                                            Gravitational centralMass) {
        double mu = centralMass.getGravitationalParameter();

        double r1_mag = r1.magnitude();
        double r2_mag = r2.magnitude();

        // Angle between position vectors
        double cosTheta = r1.dot(r2) / (r1_mag * r2_mag);
        double theta = Math.acos(Math.max(-1.0, Math.min(1.0, cosTheta)));

        // Check for degenerate case (same point or opposite points)
        if (theta < 1e-6 || Math.abs(theta - Math.PI) < 1e-6) {
            return new TransferOrbitSolution(null, 0, false,
                    "Departure and arrival points are collinear");
        }

        // Use simplified Lambert solution (assumes short-way transfer)
        // For full solution, would need to solve Lambert's problem iteratively

        // Simplified approach: assume transfer is half an ellipse
        // Semi-major axis approximation
        double c = r1.subtract(r2).magnitude(); // Chord length
        double s = (r1_mag + r2_mag + c) / 2.0; // Semi-perimeter

        // Minimum energy ellipse
        double a_min = s / 2.0;

        // For minimum time, use this semi-major axis
        double a = a_min;

        // Calculate time for this transfer using approximate formulas
        // This is simplified - full Lambert solution is more complex
        double alpha = 2.0 * Math.asin(Math.sqrt(s / (2.0 * a)));
        double beta = 2.0 * Math.asin(Math.sqrt((s - c) / (2.0 * a)));

        double transferTime;
        double sqrt = Math.sqrt(Math.pow(a, 3) / mu);
        if (theta < Math.PI) {
            // Short way
            transferTime = sqrt *
                    ((alpha - Math.sin(alpha)) - (beta - Math.sin(beta)));
        } else {
            // Long way
            transferTime = sqrt *
                    ((alpha - Math.sin(alpha)) + (beta - Math.sin(beta)));
        }

        // Create the transfer orbit from the two position vectors
        // Calculate velocity at departure point that will reach arrival point
        Vector3D v1_transfer = calculateLambertVelocity(r1, r2, transferTime,
                centralMass, true);

        // Get orbital elements from state vectors
        Orbit transferOrbit = OrbitFromStateVectors.calculateOrbitFromStateVectors(
                r1, v1_transfer, centralMass
        );

        return new TransferOrbitSolution(transferOrbit, transferTime, true, null);
    }

    /**
     * Calculate velocity for Lambert's problem (simplified)
     */
    private static Vector3D calculateLambertVelocity(Vector3D r1, Vector3D r2,
                                                     double time, Gravitational centralMass,
                                                     boolean shortWay) {
        double mu = centralMass.getGravitationalParameter();

        double r1_mag = r1.magnitude();
        double r2_mag = r2.magnitude();
        double c = r1.subtract(r2).magnitude();
        double s = (r1_mag + r2_mag + c) / 2.0;

        // Minimum energy semi-major axis
        double a = s / 2.0;

        // Calculate velocities using Lagrange coefficients (simplified)
        double f = 1.0 - r2_mag / a * (1.0 - Math.cos(Math.PI)); // Simplified
        double g = time; // Simplified
        double g_dot = 1.0 - r1_mag / a * (1.0 - Math.cos(Math.PI)); // Simplified

        // Velocity at r1
        Vector3D v1 = r2.subtract(r1.multiply(f)).divide(g);

        return v1;
    }

    /**
     * Check if a point lies on a given orbit (within tolerance)
     */
    private static boolean isPointOnOrbit(Vector3D point, Orbit orbit,
                                          double tolerance) {
        double a = orbit.semiMajorAxis();
        double e = orbit.eccentricity();

        double r = point.magnitude();

        // For an ellipse, r = a(1-e²)/(1+e*cos(ν))
        // So the radius must be between periapsis and apoapsis
        double r_peri = a * (1 - e);
        double r_apo = a * (1 + e);

        if (r < r_peri - tolerance || r > r_apo + tolerance) {
            return false;
        }

        // More rigorous check: calculate what the radius should be
        // for this true anomaly on this orbit
        double nu = OrbitFromStateVectors.calculateOrbitFromStateVectors(
                point,
                new Vector3D(0, 0, 0), // Dummy velocity
                new Gravitational() {
                    @Override
                    public String getId() {
                        return "point orbit";
                    }

                    @Override
                    public double getMass() {
                        return 1;
                    }

                    @Override
                    public Vector3D getVelocity() {
                        return null;
                    }

                    @Override
                    public double getRadius() {
                        return 0;
                    }

                    @Override
                    public Vector3D getPosition() {
                        return null;
                    }

                    @Override
                    public OrbitalSystem getSystem() {
                        return null;
                    }
                } // Dummy mass
        ).trueAnomaly(); // This is approximate

        double expected_r = a * (1 - e * e) / (1 + e * Math.cos(nu));

        return Math.abs(r - expected_r) < tolerance;
    }

