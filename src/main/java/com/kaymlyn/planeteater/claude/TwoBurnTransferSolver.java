    /**
     * Find optimal departure and arrival points for minimum delta-v transfer
     * Searches along both orbits to find the best transfer opportunity
     *
     * @param initialOrbit Starting orbit
     * @param targetOrbit Target orbit
     * @param centralMass Central body mass
     * @param numSamples Number of points to sample on each orbit
     * @return Best two-burn solution found
     */
    public static TwoBurnSolution findOptimalTransfer(Orbit initialOrbit,
                                                      Orbit targetOrbit,
                                                      Gravitational centralMass,
                                                      int numSamples) {
        TwoBurnSolution bestSolution = null;
        double minDeltaV = Double.POSITIVE_INFINITY;

        // Sample points along both orbits
        for (int i = 0; i < numSamples; i++) {
            double nu1 = (2 * Math.PI * i) / numSamples;
            Vector3D departurePoint = calculatePositionAtTrueAnomaly(initialOrbit, nu1);

            for (int j = 0; j < numSamples; j++) {
                double nu2 = (2 * Math.PI * j) / numSamples;
                Vector3D arrivalPoint = calculatePositionAtTrueAnomaly(targetOrbit, nu2);

                // Try this combination
                TwoBurnSolution solution = solveTwoBurnTransfer(
                        departurePoint, initialOrbit,
                        arrivalPoint, targetOrbit,
                        centralMass
                );

                if (solution.isFeasible() && solution.getTotalDeltaV() < minDeltaV) {
                    minDeltaV = solution.getTotalDeltaV();
                    bestSolution = solution;
                }
            }
        }

        return bestSolution;
    }

    /**
     * Calculate position at a specific true anomaly
     */
    private static Vector3D calculatePositionAtTrueAnomaly(Orbit orbit, double nu) {
        double a = orbit.semiMajorAxis();
        double e = orbit.eccentricity();
        double i = orbit.inclination();
        double omega = orbit.ascendingNode();
        double w = orbit.periapsis();

        double r = a * (1 - e * e) / (1 + e * Math.cos(nu));

        return new Vector3D( r * Math.cos(nu),r * Math.sin(nu))
                .rotateInto3spaceFrom2space(omega,i,w);
    }
