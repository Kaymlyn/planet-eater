package com.kaymlyn.planeteater.claude;

import com.kaymlyn.planeteater.simulation.celestial.CelestialBodyFactory;
import com.kaymlyn.planeteater.simulation.celestial.Star;
import com.kaymlyn.planeteater.simulation.physics.Orbit;
import com.kaymlyn.planeteater.simulation.physics.OrbitalState;
import com.kaymlyn.planeteater.simulation.physics.PhysicsConstants;
import com.kaymlyn.planeteater.simulation.physics.Vector3D;

/**
 * Minimal test case to isolate the position jump bug
 *
 * The bug manifests when:
 * 1. Create an orbit from a position/velocity
 * 2. Immediately call calculateOrbitAfterT0(0)
 * 3. The returned position doesn't match the original
 *
 * Generated by Claude (Sonnet 4.5)
 */
public class OrbitRoundTripBugTest {

    public static void main(String[] args) {
        testOrbitRoundTrip();
    }

    public static void testOrbitRoundTrip() {
        System.out.println("=======================================================");
        System.out.println("ORBIT ROUND-TRIP TEST");
        System.out.println("=======================================================\n");

        Star sun = CelestialBodyFactory.createMainSequenceStar("TestSun", 1.0);

        // Start with a simple position/velocity
        Vector3D originalPos = new Vector3D(PhysicsConstants.AU, 0, 0);
        double v = Math.sqrt(sun.getGravitationalParameter() / PhysicsConstants.AU);
        Vector3D originalVel = new Vector3D(0, v, 0);

        System.out.println("Original State:");
        System.out.printf("  Position: %s\n", formatVector(originalPos));
        System.out.printf("  Velocity: %s\n", formatVector(originalVel));
        System.out.println();

        // Create orbit from this state
        Orbit orbit = Orbit.calculateOrbit(sun, originalPos, originalVel, 0.0);

        System.out.println("Orbit Created:");
        System.out.printf("  Epoch: %.2f s\n", orbit.epoch());
        System.out.printf("  Semi-major axis: %.3e m (%.3f AU)\n",
                orbit.semiMajorAxis(), orbit.semiMajorAxis() / PhysicsConstants.AU);
        System.out.printf("  Eccentricity: %.6f\n", orbit.eccentricity());
        System.out.printf("  True Anomaly: %.6f rad (%.2f°)\n",
                orbit.trueAnomaly(), Math.toDegrees(orbit.trueAnomaly()));
        System.out.println();

        // Get state back at T=0 (should match original)
        OrbitalState recoveredState = orbit.calculateOrbitAfterT0(0.0);

        System.out.println("Recovered State (at T=0):");
        System.out.printf("  Position: %s\n", formatVector(recoveredState.position()));
        System.out.printf("  Velocity: %s\n", formatVector(recoveredState.velocity()));
        System.out.println();

        // Calculate differences
        Vector3D posDiff = recoveredState.position().subtract(originalPos);
        Vector3D velDiff = recoveredState.velocity().subtract(originalVel);
        double posError = posDiff.magnitude();
        double velError = velDiff.magnitude();

        System.out.println("Round-Trip Errors:");
        System.out.printf("  Position Error: %.6e m (%.2f km)\n", posError, posError / 1000.0);
        System.out.printf("  Velocity Error: %.6e m/s\n", velError);
        System.out.println();

        if (posError < 1000.0 && velError < 10.0) {
            System.out.println("✓ PASS: Round-trip successful within tolerance");
        } else {
            System.out.println("✗ FAIL: Round-trip has significant errors!");
            System.out.println("\nThis indicates a problem in Orbit.calculateOrbitAfterT0()");
            System.out.println("or Orbit.calculateOrbit()");
        }

        System.out.println("\n=======================================================");
        System.out.println("Testing with Lambert-like velocity (elliptical orbit)");
        System.out.println("=======================================================\n");

        // Now test with an elliptical orbit (like after a Lambert burn)
        Vector3D lambertPos = new Vector3D(PhysicsConstants.AU, 0, 0);
        Vector3D lambertVel = new Vector3D(5000, 35000, 0);  // Higher velocity

        System.out.println("Original Lambert State:");
        System.out.printf("  Position: %s\n", formatVector(lambertPos));
        System.out.printf("  Velocity: %s\n", formatVector(lambertVel));
        System.out.println();

        Orbit lambertOrbit = Orbit.calculateOrbit(sun, lambertPos, lambertVel, 0.0);

        System.out.println("Lambert Orbit Created:");
        System.out.printf("  Epoch: %.2f s\n", lambertOrbit.epoch());
        System.out.printf("  Semi-major axis: %.3e m (%.3f AU)\n",
                lambertOrbit.semiMajorAxis(), lambertOrbit.semiMajorAxis() / PhysicsConstants.AU);
        System.out.printf("  Eccentricity: %.6f\n", lambertOrbit.eccentricity());
        System.out.printf("  True Anomaly: %.6f rad (%.2f°)\n",
                lambertOrbit.trueAnomaly(), Math.toDegrees(lambertOrbit.trueAnomaly()));
        System.out.println();

        OrbitalState lambertRecovered = lambertOrbit.calculateOrbitAfterT0(0.0);

        System.out.println("Recovered Lambert State (at T=0):");
        System.out.printf("  Position: %s\n", formatVector(lambertRecovered.position()));
        System.out.printf("  Velocity: %s\n", formatVector(lambertRecovered.velocity()));
        System.out.println();

        Vector3D lambertPosDiff = lambertRecovered.position().subtract(lambertPos);
        Vector3D lambertVelDiff = lambertRecovered.velocity().subtract(lambertVel);
        double lambertPosError = lambertPosDiff.magnitude();
        double lambertVelError = lambertVelDiff.magnitude();

        System.out.println("Lambert Round-Trip Errors:");
        System.out.printf("  Position Error: %.6e m (%.2f km)\n",
                lambertPosError, lambertPosError / 1000.0);
        System.out.printf("  Velocity Error: %.6e m/s\n", lambertVelError);
        System.out.println();

        if (lambertPosError < 1000.0 && lambertVelError < 10.0) {
            System.out.println("✓ PASS: Lambert round-trip successful");
        } else {
            System.out.println("✗ FAIL: Lambert round-trip has large errors!");
            System.out.println("\nThis is likely causing the position jump in telemetry");
            System.out.printf("  Position jump would be: %.2e km\n", lambertPosError / 1000.0);
        }

        System.out.println("\n=======================================================");
    }

    private static String formatVector(Vector3D v) {
        return String.format("(%.6e, %.6e, %.6e)", v.getX(), v.getY(), v.getZ());
    }
}