package com.kaymlyn.planeteater.claude;

import com.kaymlyn.planeteater.simulation.celestial.Gravitational;
import com.kaymlyn.planeteater.simulation.physics.Vector3D;
import com.kaymlyn.planeteater.simulation.physics.OrbitalState;
import com.kaymlyn.planeteater.simulation.physics.PhysicsConstants;

/**
 * Clean-room implementation of Orbit class
 *
 * Orbital Elements (Classical Keplerian):
 * - a (semiMajorAxis): Size of the orbit
 * - e (eccentricity): Shape (0 = circle, 0-1 = ellipse)
 * - i (inclination): Tilt from reference plane
 * - Ω (ascendingNode): Where orbit crosses reference plane going up
 * - ω (periapsis): Rotation of ellipse in its plane
 * - ν (trueAnomaly): Position on the orbit (angle from periapsis)
 *
 * Reference frame:
 * - Ecliptic plane is XY (Z = 0)
 * - X-axis is the reference direction
 * - Orbital plane can be tilted (inclination)
 * - Angles measured counter-clockwise
 *
 * Key insight for round-trip consistency:
 * When going position → orbit → position:
 * 1. calculateOrbit must measure trueAnomaly in the ORBITAL PLANE (2D)
 * 2. calculateOrbitalState must interpret trueAnomaly as an angle in the ORBITAL PLANE (2D)
 * 3. Both must use the same 3D ↔ 2D transformation
 *
 * Generated by Claude (Sonnet 4.5) - Clean Room Implementation
 */
public record OrbitCleanRoom(
        double semiMajorAxis,      // a: meters
        double eccentricity,       // e: 0 to <1
        double inclination,        // i: radians, 0 to π
        double ascendingNode,      // Ω: radians, 0 to 2π
        double periapsis,          // ω: radians, 0 to 2π
        double trueAnomaly,        // ν: radians, 0 to 2π
        Gravitational centerBody,  // What we're orbiting
        double epoch               // When these elements were measured
) {

    // ========== STATIC FACTORY: CREATE ORBIT FROM POSITION/VELOCITY ==========

    /**
     * Calculate orbital elements from current 3D position and velocity
     *
     * CRITICAL: This method must measure trueAnomaly in the orbital plane (2D),
     * not in 3D space, to ensure round-trip consistency.
     *
     * Algorithm:
     * 1. Calculate energy and angular momentum (3D vectors)
     * 2. Derive a, e, i, Ω, ω from these
     * 3. PROJECT position into 2D orbital plane
     * 4. Measure trueAnomaly as angle in that 2D plane
     *
     * @param centerBody What we're orbiting
     * @param position 3D position vector (m)
     * @param velocity 3D velocity vector (m/s)
     * @return Orbit elements
     */
    public static OrbitCleanRoom calculateOrbit(
            Gravitational centerBody,
            Vector3D position,
            Vector3D velocity) {

        double gravitationalParameter = centerBody.getGravitationalParameter();
        double radiusMagnitude = position.magnitude();
        double velocityMagnitudeSquared = velocity.magnitudeSquared();

        // === STEP 1: Energy and Semi-Major Axis ===
        // Specific orbital energy: ε = v²/2 - μ/r
        double specificEnergy = velocityMagnitudeSquared / 2.0 -
                gravitationalParameter / radiusMagnitude;

        // Semi-major axis: a = -μ / (2ε)
        double semiMajorAxis = -gravitationalParameter / (2.0 * specificEnergy);

        // === STEP 2: Angular Momentum and Inclination ===
        // Specific angular momentum vector: h = r × v
        Vector3D angularMomentumVector = position.cross(velocity);
        double angularMomentumMagnitude = angularMomentumVector.magnitude();

        // Inclination: angle between h and Z-axis
        // cos(i) = h_z / |h|
        double inclination = Math.acos(
                angularMomentumVector.getZ() / angularMomentumMagnitude
        );

        // === STEP 3: Eccentricity Vector ===
        // e_vec = (v × h)/μ - r/|r|
        Vector3D eccentricityVector = velocity.cross(angularMomentumVector)
                .divide(gravitationalParameter)
                .subtract(position.normalize());

        double eccentricity = eccentricityVector.magnitude();

        // === STEP 4: Node Vector and Ascending Node ===
        // n = Z × h (points toward ascending node)
        Vector3D nodeVector = Vector3D.UNIT_Z.cross(angularMomentumVector);
        double nodeVectorMagnitude = nodeVector.magnitude();

        double ascendingNode;
        if (nodeVectorMagnitude > 1e-10) {
            // Ω = arccos(n_x / |n|)
            ascendingNode = Math.acos(nodeVector.getX() / nodeVectorMagnitude);

            // Quadrant check: if n_y < 0, Ω is in [π, 2π]
            if (nodeVector.getY() < 0) {
                ascendingNode = 2.0 * Math.PI - ascendingNode;
            }
        } else {
            // Orbit is not inclined, node is undefined
            ascendingNode = 0.0;
        }

        // === STEP 5: Argument of Periapsis ===
        double argumentOfPeriapsis;
        if (nodeVectorMagnitude > 1e-10 && eccentricity > 1e-10) {
            // ω = arccos(n · e / (|n||e|))
            argumentOfPeriapsis = Math.acos(
                    nodeVector.dot(eccentricityVector) /
                            (nodeVectorMagnitude * eccentricity)
            );

            // Quadrant check: if e_z < 0, ω is in [π, 2π]
            if (eccentricityVector.getZ() < 0) {
                argumentOfPeriapsis = 2.0 * Math.PI - argumentOfPeriapsis;
            }
        } else {
            // Circular or non-inclined orbit, periapsis is undefined
            argumentOfPeriapsis = 0.0;
        }

        // === STEP 6: True Anomaly (CRITICAL - MEASURE IN 2D ORBITAL PLANE) ===

        // First, rotate position into the orbital plane coordinate system
        // This removes the 3D rotation (Ω, i, ω) to get pure 2D position
        Vector3D position2D = rotateFrom3DTo2D(
                position,
                ascendingNode,
                inclination,
                argumentOfPeriapsis
        );

        // Now measure angle in THIS 2D PLANE
        // This is the angle from the +X axis (periapsis direction) to the position
        double trueAnomaly = Math.atan2(position2D.getY(), position2D.getX());

        // Normalize to [0, 2π]
        if (trueAnomaly < 0) {
            trueAnomaly += 2.0 * Math.PI;
        }

        return new OrbitCleanRoom(
                semiMajorAxis,
                eccentricity,
                inclination,
                ascendingNode,
                argumentOfPeriapsis,
                trueAnomaly,
                centerBody,
                centerBody.getSystem().getCurrentTime()
        );
    }

    // ========== CALCULATE POSITION/VELOCITY FROM ORBIT ==========

    /**
     * Calculate current orbital state from elements
     *
     * CRITICAL: This must interpret trueAnomaly as an angle in the 2D orbital plane,
     * then rotate that 2D position into 3D space.
     *
     * Algorithm:
     * 1. Calculate radius at current trueAnomaly
     * 2. Calculate position in 2D orbital plane (X = r*cos(ν), Y = r*sin(ν))
     * 3. Calculate velocity in 2D orbital plane
     * 4. Rotate both to 3D using (Ω, i, ω)
     *
     * @return OrbitalState with position and velocity
     */
    public OrbitalState calculateOrbitalState() {
        double gravitationalParameter = centerBody.getGravitationalParameter();

        // === STEP 1: Radius at True Anomaly ===
        // r = a(1-e²) / (1 + e*cos(ν))
        double semiLatusRectum = semiMajorAxis * (1.0 - eccentricity * eccentricity);
        double radius = semiLatusRectum / (1.0 + eccentricity * Math.cos(trueAnomaly));

        // === STEP 2: Position in 2D Orbital Plane ===
        Vector3D position2D = new Vector3D(
                radius * Math.cos(trueAnomaly),
                radius * Math.sin(trueAnomaly),
                0.0
        );

        // === STEP 3: Velocity in 2D Orbital Plane ===
        // Radial component: v_r = sqrt(μ/p) * e * sin(ν)
        // Tangential component: v_t = sqrt(μ/p) * (1 + e*cos(ν))

        double sqrtMuOverP = Math.sqrt(gravitationalParameter / semiLatusRectum);
        double radialVelocity = sqrtMuOverP * eccentricity * Math.sin(trueAnomaly);
        double tangentialVelocity = sqrtMuOverP * (1.0 + eccentricity * Math.cos(trueAnomaly));

        // Convert to Cartesian in orbital plane
        Vector3D velocity2D = new Vector3D(
                radialVelocity * Math.cos(trueAnomaly) - tangentialVelocity * Math.sin(trueAnomaly),
                radialVelocity * Math.sin(trueAnomaly) + tangentialVelocity * Math.cos(trueAnomaly),
                0.0
        );

        // === STEP 4: Rotate to 3D ===
        Vector3D position3D = rotateFrom2DTo3D(
                position2D,
                ascendingNode,
                inclination,
                periapsis
        );

        Vector3D velocity3D = rotateFrom2DTo3D(
                velocity2D,
                ascendingNode,
                inclination,
                periapsis
        );

        return new OrbitalState(position3D, velocity3D,
                new com.kaymlyn.planeteater.simulation.physics.Orbit(
                        semiMajorAxis, eccentricity, inclination,
                        ascendingNode, periapsis, trueAnomaly,
                        centerBody, epoch
                )
        );
    }

    // ========== COORDINATE TRANSFORMATIONS ==========

    /**
     * Rotate a 2D orbital plane vector to 3D space
     *
     * Rotation sequence (in order):
     * 1. Rotate by ω (argument of periapsis) in the orbital plane
     * 2. Rotate by i (inclination) around the node line
     * 3. Rotate by Ω (ascending node) around the Z-axis
     *
     * This uses the standard rotation matrix from orbital mechanics.
     */
    private static Vector3D rotateFrom2DTo3D(
            Vector3D vec2D,
            double omega,
            double inclinationAngle,
            double argumentOfPeriapsisAngle) {

        double x2d = vec2D.getX();
        double y2d = vec2D.getY();

        // Precompute trig functions
        double cosOmega = Math.cos(omega);
        double sinOmega = Math.sin(omega);
        double cosI = Math.cos(inclinationAngle);
        double sinI = Math.sin(inclinationAngle);
        double cosW = Math.cos(argumentOfPeriapsisAngle);
        double sinW = Math.sin(argumentOfPeriapsisAngle);

        // Combined rotation matrix
        double x3d = x2d * (cosOmega * cosW - sinOmega * sinW * cosI) -
                y2d * (cosOmega * sinW + sinOmega * cosW * cosI);

        double y3d = x2d * (sinOmega * cosW + cosOmega * sinW * cosI) -
                y2d * (sinOmega * sinW - cosOmega * cosW * cosI);

        double z3d = x2d * (sinW * sinI) +
                y2d * (cosW * sinI);

        return new Vector3D(x3d, y3d, z3d);
    }

    /**
     * Rotate a 3D space vector to 2D orbital plane
     *
     * This is the INVERSE of rotateFrom2DTo3D.
     * Uses the transpose of the rotation matrix (since rotation matrices are orthogonal).
     */
    private static Vector3D rotateFrom3DTo2D(
            Vector3D vec3D,
            double omega,
            double inclinationAngle,
            double argumentOfPeriapsisAngle) {

        double x3d = vec3D.getX();
        double y3d = vec3D.getY();
        double z3d = vec3D.getZ();

        // Precompute trig functions
        double cosOmega = Math.cos(omega);
        double sinOmega = Math.sin(omega);
        double cosI = Math.cos(inclinationAngle);
        double sinI = Math.sin(inclinationAngle);
        double cosW = Math.cos(argumentOfPeriapsisAngle);
        double sinW = Math.sin(argumentOfPeriapsisAngle);

        // Transpose of the rotation matrix
        double x2d = x3d * (cosOmega * cosW - sinOmega * sinW * cosI) +
                y3d * (sinOmega * cosW + cosOmega * sinW * cosI) +
                z3d * (sinW * sinI);

        double y2d = -x3d * (cosOmega * sinW + sinOmega * cosW * cosI) -
                y3d * (sinOmega * sinW - cosOmega * cosW * cosI) +
                z3d * (cosW * sinI);

        // Z component should be zero (we're in a plane)
        return new Vector3D(x2d, y2d, 0.0);
    }
}