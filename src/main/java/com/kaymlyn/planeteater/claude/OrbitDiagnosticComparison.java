        System.out.printf("  a = %.6e m\n", originalOrbit.semiMajorAxis());
        System.out.printf("  e = %.10f\n", originalOrbit.eccentricity());
        System.out.printf("  i = %.10f rad (%.6f°)\n",
                originalOrbit.inclination(), Math.toDegrees(originalOrbit.inclination()));
        System.out.printf("  Ω = %.10f rad (%.6f°)\n",
                originalOrbit.ascendingNode(), Math.toDegrees(originalOrbit.ascendingNode()));
        System.out.printf("  ω = %.10f rad (%.6f°)\n",
                originalOrbit.periapsis(), Math.toDegrees(originalOrbit.periapsis()));
        System.out.printf("  ν = %.10f rad (%.6f°)\n",
                originalOrbit.trueAnomaly(), Math.toDegrees(originalOrbit.trueAnomaly()));
        System.out.printf("  epoch = %.6f s\n", originalOrbit.epoch());
        System.out.println();

        // Calculate state
        OrbitalState originalState = originalOrbit.calculateOrbitalState();

        System.out.println("Recovered state:");
        System.out.println("  position: " + originalState.position());
        System.out.println("  velocity: " + originalState.velocity());
        System.out.println();

        // Calculate errors
        double originalPosError = originalState.position().subtract(pos).magnitude();
        double originalVelError = originalState.velocity().subtract(vel).magnitude();

        System.out.printf("Position error: %.6e m (%.3f km)\n",
                originalPosError, originalPosError / 1000.0);
        System.out.printf("Velocity error: %.6e m/s\n", originalVelError);
        System.out.println();

        // === CLEAN ROOM IMPLEMENTATION ===
        System.out.println("--- CLEAN ROOM IMPLEMENTATION ---");
        OrbitCleanRoom cleanOrbit = OrbitCleanRoom.calculateOrbit(sun, pos, vel);

        System.out.println("Orbital elements:");
        System.out.printf("  a = %.6e m\n", cleanOrbit.semiMajorAxis());
        System.out.printf("  e = %.10f\n", cleanOrbit.eccentricity());
        System.out.printf("  i = %.10f rad (%.6f°)\n",
                cleanOrbit.inclination(), Math.toDegrees(cleanOrbit.inclination()));
