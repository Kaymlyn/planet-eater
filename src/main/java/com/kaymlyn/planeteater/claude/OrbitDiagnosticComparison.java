        System.out.printf("  ω = %.10f rad (%.6f°)\n",
                cleanOrbit.periapsis(), Math.toDegrees(cleanOrbit.periapsis()));
        System.out.printf("  ν = %.10f rad (%.6f°)\n",
                cleanOrbit.trueAnomaly(), Math.toDegrees(cleanOrbit.trueAnomaly()));
        System.out.printf("  epoch = %.6f s\n", cleanOrbit.epoch());
        System.out.println();

        // Calculate state
        OrbitalState cleanState = cleanOrbit.calculateOrbitalState();

        System.out.println("Recovered state:");
        System.out.println("  position: " + cleanState.position());
        System.out.println("  velocity: " + cleanState.velocity());
        System.out.println();

