    /**
     * Build Lambert transfer itinerary.
     */
    private static Itinerary buildLambertItinerary(
            Spacecraft spacecraft,
            Orbiter destination,
            boolean land,
            ManeuverDetails start,
            Orbit targetOrbit,
            double transferTime) {

        Itinerary itinerary = new Itinerary(start.getStartTime());

        // Predict target position at arrival
        OrbitalState futureTarget = targetOrbit.calculateOrbitAfterT0(
                start.getEndTime() + transferTime - targetOrbit.epoch());

        // Lambert transfer (2 burns, 1 coast)
        ManeuverDetails transfer = buildLambertTransfer(
                futureTarget.position(),
                futureTarget.velocity(),
                transferTime,
                start
        );

        // Arrival
        buildArrival(destination, land, transfer, targetOrbit);

        itinerary.setInitialManeuver(start);
        itinerary.setFinalDestination(destination);
        itinerary.setFinalSpacecraftState(
                land ? Spacecraft.SpacecraftState.DOCKED : Spacecraft.SpacecraftState.ORBITING);

        itinerary.validateAgainstSpacecraft(spacecraft);
        return itinerary;
    }

    /**
     * Build arrival sequence (common to all transfers).
     */
    private static ManeuverDetails buildArrival(
            Orbiter destination,
            boolean land,
            ManeuverDetails transfer,
            Orbit targetOrbit) {

        if (destination instanceof Gravitational grav) {

            // Insert into orbit
            ManeuverDetails insertion = buildOrbitalInsertion(
                    grav,
                    grav.getStandardOrbitalAltitude(),
                    transfer
            );

            if (land) {
                // Land on surface
                return insertion.finallyLand(grav);
            } else {
                // Stay in orbit
                return insertion;
            }
        } else {
            // Match velocity with station/satellite
            Vector3D matchVel = targetOrbit.calculateVelocityVectorAtPosition(
                    transfer.getEndingPosition());

            return transfer.thenBurn(matchVel, "Match Velocity with " + destination.getId());
        }
    }

    /**
     * Select best transfer for optimization goal.
     */
    public static TransferOption selectBestTransfer(
            List<TransferOption> options,
            OptimizationGoal goal) {

        if (options.isEmpty()) {
            return null;
        }

        return switch (goal) {
            case MINIMUM_TIME -> options.stream()
                    .min(Comparator.comparingDouble(opt -> opt.getItinerary().getTotalFlightTime()))
                    .orElse(null);

            case MINIMUM_DELTAV -> options.stream()
                    .min(Comparator.comparingDouble(opt ->
                            opt.getItinerary().getTravelDeltaV() +
                                    opt.getItinerary().getLaunchDeltaV() +
                                    opt.getItinerary().getLandingDeltaV()))
                    .orElse(null);

            case BALANCED -> options.stream()
                    .min(Comparator.comparingDouble(TransferOption::getEfficiencyScore))
                    .orElse(null);
        };
    }

    /**
     * Calculate minimum transfer time (Hohmann half-period).
     */
    private static double calculateMinimumTransferTime(Orbit origin, Orbit target) {
        double a_transfer = (origin.semiMajorAxis() + target.semiMajorAxis()) / 2.0;
        double mu = origin.centerBody().getGravitationalParameter();
        return Math.PI * Math.sqrt(Math.pow(a_transfer, 3) / mu);
    }
