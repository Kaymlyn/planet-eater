package com.kaymlyn.planeteater.simulation.physics;

import com.kaymlyn.planeteater.simulation.celestial.Gravitational;
import com.kaymlyn.planeteater.simulation.celestial.OrbitingBody;
import com.kaymlyn.planeteater.simulation.celestial.Orbiter;
import com.kaymlyn.planeteater.simulation.celestial.Star;
import com.kaymlyn.planeteater.simulation.vehicles.Satellite;
import lombok.Getter;
import lombok.ToString;

import java.util.UUID;

/**
 * Represents a single maneuver (burn or coast) in a flight plan.
 * Stores position/velocity states, NOT orbits.
 * All time parameters are explicitly absolute simulation times.
 * Orbits are calculated on demand for trajectory prediction during coasts,
 * but are not stored as persistent state.
 *
 * Generated by Claude (Sonnet 4.5) - Absolute Time Refactor
 */
@Getter
@ToString(exclude = {"previous", "next"})
public class ManeuverDetails {
    private final String id;
    private final Vector3D startingPosition;
    private final Vector3D startingVelocity;
    private final Vector3D endingPosition;
    private final Vector3D endingVelocity;
    private final double deltaV;
    private final Gravitational referenceBody;  // For trajectory calculations
    private final double timeToExecute;
    private final double startTime;              // Absolute simulation time

    // Chain references
    private final ManeuverDetails previous;
    private ManeuverDetails next;

    private boolean terminus;

    private ManeuverDetails(
            String id,
            Vector3D startingPosition,
            Vector3D startingVelocity,
            Vector3D endingPosition,
            Vector3D endingVelocity,
            double deltaV,
            Gravitational referenceBody,
            double timeToExecute,
            double startTime,
            ManeuverDetails previous,
            boolean terminus) {

        this.id = id;
        this.startingPosition = startingPosition;
        this.startingVelocity = startingVelocity;
        this.endingPosition = endingPosition;
        this.endingVelocity = endingVelocity;
        this.deltaV = deltaV;
        this.referenceBody = referenceBody;
        this.timeToExecute = timeToExecute;
        this.startTime = startTime;
        this.previous = previous;
        this.next = null;
        this.terminus = terminus;

        if (previous != null) {
            previous.next = this;
        }
    }

    /**
     * Get the absolute simulation time when this maneuver completes.
     */
    public double getEndTime() {
        return startTime + timeToExecute;
    }

    // ==================== STATIC FACTORY METHODS ====================

    /**
     * Create the first maneuver in a chain from initial state.
     *
     * @param id Identifier for this maneuver
     * @param initialPosition Starting position
     * @param initialVelocity Starting velocity
     * @param referenceBody Gravitational body for trajectory calculations
     * @param startTime Absolute simulation time when this state is valid
     */
    public static ManeuverDetails createInitial(
            String id,
            Vector3D initialPosition,
            Vector3D initialVelocity,
            Gravitational referenceBody,
            double startTime) {

        return new ManeuverDetails(
                id != null ? id : "Initial-" + UUID.randomUUID(),
                initialPosition,
                initialVelocity,
                initialPosition,
                initialVelocity,
                0.0,
                referenceBody,
                0.0,
                startTime,
                null,
                false);
    }

    /**
     * Create takeoff maneuver from a gravitational body to standard orbit.
     *
     * @param launchBody The body to launch from
     * @param startTime Absolute simulation time when launch begins
     */
    public static ManeuverDetails takeOff(
            Gravitational launchBody,
            double startTime) {

        // Calculate orbital parameters
        double orbitalRadius = launchBody.getStandardOrbitalRadius();
        Vector3D orbitalVelocity = launchBody.getStandardCircularOrbitVector();
        Vector3D orbitalPosition = launchBody.getStandardCircularOrbitPosition(Vector3D.ZERO);

        // FIXED: Determine launch direction from orbital position
        // This ensures starting position is on surface in direction of orbit
        Vector3D launchDirection = orbitalPosition
                .subtract(launchBody.getPosition())
                .normalize();

        // FIXED: Start at surface, not at body center
        Vector3D surfacePosition = launchBody.getPosition()
                .add(launchDirection.multiply(launchBody.getRadius()));

        // Calculate delta-V required for launch
        double launchDeltaV = launchBody.getEscapeVelocityFromRadius(orbitalRadius) +
                (launchBody.getOrbitalVelocity(orbitalRadius) -
                        Math.sqrt(launchBody.getGravitationalParameter() / orbitalRadius));

        // Calculate launch time (ascent from surface to orbit)
        double launchTime = launchBody.getStandardOrbitalAltitude() * 2 /
                orbitalVelocity.subtract(launchBody.getVelocity()).magnitude();

        return new ManeuverDetails(
                "Take off to Standard Orbit (" + orbitalRadius + "m) from " + launchBody.getId(),
                surfacePosition,           // FIXED: at surface, not center
                launchBody.getVelocity(),  // Inherits body's orbital motion
                orbitalPosition,           // Already corrected by getStandardCircularOrbitPosition()
                orbitalVelocity,
                launchDeltaV,
                launchBody,
                launchTime,
                startTime,
                null,
                false);
    }

    /**
     * Create detach maneuver from a satellite.
     *
     * @param satellite The satellite to detach from
     * @param startTime Absolute simulation time when detachment occurs
     */
    public static ManeuverDetails detach(Satellite satellite, double startTime) {
        return new ManeuverDetails(
                "Detach from " + satellite.getId(),
                satellite.getPosition(),
                satellite.getVelocity(),
                satellite.getPosition(),
                satellite.getVelocity(),
                0.0001,
                satellite.getParentBody(),
                0.0,
                startTime,
                null,
                false);
    }

    // ==================== BUILDER METHODS ====================

    /**
     * Create an impulsive burn (instant velocity change).
     *
     * @param newVelocity The velocity after the burn
     * @param description Human-readable description
     */
    public ManeuverDetails thenBurn(Vector3D newVelocity, String description) {
        return new ManeuverDetails(
                description != null ? description : "Burn-" + UUID.randomUUID(),
                this.endingPosition,
                this.endingVelocity,
                this.endingPosition,
                newVelocity,
                newVelocity.subtract(this.endingVelocity).magnitude(),
                this.referenceBody,
                0.0,
                getEndTime(),
                this,
                false);
    }

    /**
     * Create a coast maneuver with explicit reference body.
     *
     * Use this when the spacecraft transitions between spheres of influence.
     * For example, a Hohmann transfer from Earth to Venus should coast around
     * the Sun, not Earth.
     *
     * @param coastTime Duration of coast in seconds
     * @param newReferenceBody The gravitational body to orbit during this coast
     * @return New coast maneuver with specified reference body
     * @throws IllegalArgumentException if coastTime <= 0
     *
     * Generated by Claude (Sonnet 4.5)
     */
    public ManeuverDetails thenCoastAroundBody(double coastTime, Gravitational newReferenceBody) {
        if (coastTime <= 0.0) {
            throw new IllegalArgumentException("Non-positive coast times not allowed.");
        }

        // Convert absolute positions to body-relative coordinates
        // for the NEW reference body (e.g., Sun instead of Earth)
        Vector3D relativePosition = endingPosition.subtract(newReferenceBody.getPosition());
        Vector3D relativeVelocity = endingVelocity.subtract(newReferenceBody.getVelocity());

        // Calculate trajectory using NEW reference body
        Orbit trajectory = Orbit.fromState(newReferenceBody, relativePosition, relativeVelocity);

        // Calculate absolute times for this maneuver
        double currentTime = getEndTime();
        double arrivalTime = currentTime + coastTime;

        // Get predicted state in body-relative frame
        OrbitalState endState = trajectory.stateAt(arrivalTime, currentTime);

        // Convert predicted state back to absolute coordinates
        Vector3D absoluteEndPosition = endState.position().add(newReferenceBody.getPosition());
        Vector3D absoluteEndVelocity = endState.velocity().add(newReferenceBody.getVelocity());

        return new ManeuverDetails(
                "Coast around " + newReferenceBody.getId() + " - " + UUID.randomUUID(),
                this.endingPosition,      // Starting absolute position
                this.endingVelocity,      // Starting absolute velocity
                absoluteEndPosition,      // Ending absolute position
                absoluteEndVelocity,      // Ending absolute velocity
                0.0,
                newReferenceBody,         // KEY: Use NEW reference body
                coastTime,
                getEndTime(),
                this,
                false);
    }

    /**
     * Create a coast maneuver using inherited reference body.
     *
     * Use this for coasts within a single sphere of influence (e.g., orbiting
     * around Earth without leaving Earth's SOI).
     *
     * @param coastTime Duration of coast in seconds
     * @return New coast maneuver with inherited reference body
     * @throws IllegalArgumentException if coastTime <= 0
     *
     * Generated by Claude (Sonnet 4.5)
     */
    public ManeuverDetails thenCoast(double coastTime) {
        return thenCoastAroundBody(coastTime, this.referenceBody);
    }

    /**
     * Land on a gravitational body.
     *
     * @param landingTarget The body to land on
     */
    public ManeuverDetails finallyLand(Gravitational landingTarget) {
        if (landingTarget instanceof Star) {
            this.terminus = true;
            return this;
        }

        if (!(landingTarget instanceof Orbiter destinationOrbiter)) {
            throw new IllegalArgumentException(
                    "Landing target must be an Orbiter to calculate future position");
        }

        double arrivalTime = this.getEndTime();

        // Predict where planet will be at arrival using absolute time
        double systemCurrentTime = destinationOrbiter.getParentBody().getSystem().getCurrentTime();

        Orbit planetTrajectory = Orbit.fromState(
                destinationOrbiter.getParentBody(),
                destinationOrbiter.getPosition(),
                destinationOrbiter.getVelocity()
        );

        // NEW: Use absolute time API
        OrbitalState futureDestination = planetTrajectory.stateAt(arrivalTime, systemCurrentTime);

        // Calculate landing time
        double altitudeToCover = landingTarget.getStandardOrbitalAltitude();
        double averageDescentSpeed = landingTarget.getSurfaceEscapeVelocity() / 2.0;
        double descentTime = altitudeToCover / averageDescentSpeed;

        double deorbitTime = Math.PI * 0.5 * Math.sqrt(
                Math.pow(landingTarget.getStandardOrbitalRadius(), 3) /
                        landingTarget.getGravitationalParameter());

        double totalLandingTime = deorbitTime + descentTime;
        double landingDeltaV = landingTarget.getEscapeVelocityFromRadius(
                landingTarget.getStandardOrbitalRadius());

        return new ManeuverDetails(
                "Landing-" + landingTarget.getId(),
                this.endingPosition,
                this.endingVelocity,
                futureDestination.position(),
                futureDestination.velocity(),
                landingDeltaV,
                landingTarget,
                totalLandingTime,
                this.getEndTime(),
                this,
                true);
    }

    // ==================== TRAJECTORY PREDICTION (ABSOLUTE TIME) ====================

    /**
     * Predict position at a specific absolute simulation time during this maneuver.
     *
     * For coasts, uses 2-body approximation.
     * For burns, returns ending position (instantaneous).
     *
     * @param absoluteTime Absolute simulation time to query
     * @return Predicted position at that time
     * @throws IllegalArgumentException if absoluteTime outside maneuver window
     */
    public Vector3D predictPositionAt(double absoluteTime) {
        if (absoluteTime < startTime || absoluteTime > getEndTime()) {
            throw new IllegalArgumentException(
                    String.format("Time %.1f outside maneuver range [%.1f, %.1f]",
                            absoluteTime, startTime, getEndTime()));
        }

        if (timeToExecute == 0.0) {
            // Burn - instantaneous
            return endingPosition;
        }

        // Coast - calculate trajectory using absolute time
        Orbit trajectory = Orbit.fromState(referenceBody, startingPosition, startingVelocity);

        // This maneuver started at startTime, we want position at absoluteTime
        return trajectory.stateAt(absoluteTime, startTime).position();
    }

    /**
     * Predict velocity at a specific absolute simulation time during this maneuver.
     *
     * @param absoluteTime Absolute simulation time to query
     * @return Predicted velocity at that time
     * @throws IllegalArgumentException if absoluteTime outside maneuver window
     */
    public Vector3D predictVelocityAt(double absoluteTime) {
        if (absoluteTime < startTime || absoluteTime > getEndTime()) {
            throw new IllegalArgumentException(
                    String.format("Time %.1f outside maneuver range [%.1f, %.1f]",
                            absoluteTime, startTime, getEndTime()));
        }

        if (timeToExecute == 0.0) {
            // Burn - instantaneous
            return endingVelocity;
        }

        // Coast - calculate trajectory using body-relative coordinates

        // FIXED: Convert to body-relative for orbit calculation
        Vector3D relativeStartPosition = startingPosition.subtract(referenceBody.getPosition());
        Vector3D relativeStartVelocity = startingVelocity.subtract(referenceBody.getVelocity());

        Orbit trajectory = Orbit.fromState(referenceBody, relativeStartPosition, relativeStartVelocity);

        // Get predicted state in body-relative frame
        OrbitalState predictedState = trajectory.stateAt(absoluteTime, startTime);

        // FIXED: Convert back to absolute coordinates
        return predictedState.velocity().add(referenceBody.getVelocity());
    }

    /**
     * Get the first maneuver in this chain.
     */
    public ManeuverDetails getFirst() {
        ManeuverDetails current = this;
        while (current.previous != null) {
            current = current.previous;
        }
        return current;
    }


}