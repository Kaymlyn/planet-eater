package com.kaymlyn.planeteater.simulation.physics;

public class LambertUtility {
    /**
     * Solve Lambert's problem using the universal variable method.
     *
     * Finds the departure and arrival velocity vectors for a conic arc
     * connecting position r1 to position r2 in the given time of flight.
     * Handles all transfer geometries including near-0 and near-180 degree
     * transfer angles.
     *
     * Algorithm: universal variable iteration (Bate, Mueller, White formulation)
     * with Stumpff c2/c3 functions for numerical stability across conic types.
     *
     * @param r1           departure position vector (m)
     * @param r2           arrival position vector (m)
     * @param transferTime time of flight (s), must be positive
     * @param mu           gravitational parameter of central body (m^3/s^2)
     * @return LambertSolution containing departure and arrival velocity vectors,
     *         or null if no solution converged within tolerance
     *
     * Generated by Claude (Sonnet 4.5)
     */
    static LambertSolution solveLambert(
            Vector3D r1,
            Vector3D r2,
            double transferTime,
            double mu) {

        double r1Magnitude = r1.magnitude();
        double r2Magnitude = r2.magnitude();

        // Determine transfer angle (0 to 2*pi)
        double cosTransferAngle = r1.dot(r2) / (r1Magnitude * r2Magnitude);
        cosTransferAngle = Math.max(-1.0, Math.min(1.0, cosTransferAngle));

        // Use cross product z-component to determine orbit direction
        double crossZ = r1.getX() * r2.getY() - r1.getY() * r2.getX();
        double transferAngle = crossZ >= 0.0
                ? Math.acos(cosTransferAngle)
                : 2.0 * Math.PI - Math.acos(cosTransferAngle);

        if (transferAngle < 1e-10 || Math.abs(transferAngle - Math.PI) < 1e-10) {
            // Degenerate geometry: collinear vectors, indeterminate plane
            return null;
        }

        // A parameter (positive for prograde transfers)
        double sqrtArg = r1Magnitude * r2Magnitude * (1.0 + cosTransferAngle);
        if (sqrtArg < 1e-20) {
            return null;
        }
        double universalA = Math.signum(Math.sin(transferAngle)) * Math.sqrt(sqrtArg);

        // Universal variable iteration: find z such that time-of-flight matches
        double zLow = -4.0 * Math.PI * Math.PI;
        double zHigh = 4.0 * Math.PI * Math.PI;
        double universalZ = 0.0;

        final int MAX_ITERATIONS = 200;
        final double CONVERGENCE_TOLERANCE = 1e-6;

        for (int iteration = 0; iteration < MAX_ITERATIONS; iteration++) {
            double zMid = (zLow + zHigh) / 2.0;

            double[] stumpff = stumpffFunctions(zMid);
            double c2 = stumpff[0];
            double c3 = stumpff[1];

            double sqrtY = r1Magnitude + r2Magnitude
                    + universalA * (zMid * c3 - 1.0) / Math.sqrt(c2);
            if (universalA > 0.0 && sqrtY < 0.0) {
                zLow = zMid;
                continue;
            }

            double universalY = Math.max(sqrtY, 0.0);
            double universalX = Math.sqrt(universalY / c2);
            double computedTime = (Math.pow(universalX, 3) * c3
                    + universalA * Math.sqrt(universalY)) / Math.sqrt(mu);

            if (Math.abs(computedTime - transferTime) < CONVERGENCE_TOLERANCE) {
                universalZ = zMid;
                break;
            }

            if (computedTime < transferTime) {
                zLow = zMid;
            } else {
                zHigh = zMid;
            }
            universalZ = zMid;
        }

        // Recover Lagrange f and g coefficients
        double[] stumpff = stumpffFunctions(universalZ);
        double c2 = stumpff[0];
        double c3 = stumpff[1];

        double universalY = r1Magnitude + r2Magnitude
                + universalA * (universalZ * c3 - 1.0) / Math.sqrt(c2);
        if (universalY < 0.0) {
            return null;
        }

        double lagrangeF = 1.0 - universalY / r1Magnitude;
        double lagrangeG = universalA * Math.sqrt(universalY / mu);
        double lagrangeGDot = 1.0 - universalY / r2Magnitude;

        if (Math.abs(lagrangeG) < 1e-20) {
            return null;
        }

        // Departure and arrival velocities from Lagrange coefficients:
        //   v1 = (r2 - f*r1) / g
        //   v2 = (gDot*r2 - r1) / g
        Vector3D departureVelocity = r2.subtract(r1.multiply(lagrangeF)).divide(lagrangeG);
        Vector3D arrivalVelocity = r2.multiply(lagrangeGDot).subtract(r1).divide(lagrangeG);

        return new LambertSolution(departureVelocity, arrivalVelocity);
    }

    /**
     * Stumpff functions c2 and c3 used in the universal variable Lambert solver.
     *
     * c2(z) and c3(z) are entire functions that provide numerical stability
     * across elliptic (z > 0), parabolic (z = 0), and hyperbolic (z < 0)
     * trajectories.
     *
     * For z > 0 (elliptic):
     *   c2 = (1 - cos(sqrt(z))) / z
     *   c3 = (sqrt(z) - sin(sqrt(z))) / sqrt(z^3)
     *
     * For z < 0 (hyperbolic):
     *   c2 = (1 - cosh(sqrt(-z))) / z
     *   c3 = (sinh(sqrt(-z)) - sqrt(-z)) / sqrt((-z)^3)
     *
     * For z near 0 (parabolic): series expansion
     *   c2 = 1/2 - z/24 + z^2/720 - ...
     *   c3 = 1/6 - z/120 + z^2/5040 - ...
     *
     * @param z universal variable squared
     * @return double[]{c2, c3}
     *
     * Generated by Claude (Sonnet 4.5)
     */
    private static double[] stumpffFunctions(double z) {
        if (z > 1e-6) {
            double sqrtZ = Math.sqrt(z);
            double c2 = (1.0 - Math.cos(sqrtZ)) / z;
            double c3 = (sqrtZ - Math.sin(sqrtZ)) / (sqrtZ * z);
            return new double[]{c2, c3};
        } else if (z < -1e-6) {
            double sqrtNegZ = Math.sqrt(-z);
            double c2 = (1.0 - Math.cosh(sqrtNegZ)) / z;
            double c3 = (Math.sinh(sqrtNegZ) - sqrtNegZ) / (sqrtNegZ * (-z));
            return new double[]{c2, c3};
        } else {
            // Series expansion near z = 0
            double c2 = 0.5 - z / 24.0 + z * z / 720.0;
            double c3 = 1.0 / 6.0 - z / 120.0 + z * z / 5040.0;
            return new double[]{c2, c3};
        }
    }

    /**
     * Departure and arrival velocity vectors from a Lambert solution.
     *
     * Generated by Claude (Sonnet 4.5)
     */
    record LambertSolution(Vector3D departureVelocity, Vector3D arrivalVelocity) {}
}
