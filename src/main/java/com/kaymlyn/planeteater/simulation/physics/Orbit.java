package com.kaymlyn.planeteater.simulation.physics;

import com.kaymlyn.planeteater.simulation.celestial.Gravitational;

/**
 * Represents the mathematical relationship between position, velocity, and gravity
 * in a 2-body system at a specific instant in time.
 * All temporal operations now use absolute time from OrbitalSystem.getCurrentTime()
 * instead of ambiguous "elapsed time" calculations. This eliminates epoch confusion.
 * This is NOT a representation of persistent state. In n-body systems, orbital elements
 * are only valid at the instant they're calculated. The actual trajectory will diverge
 * immediately due to perturbations from other bodies.
 * Use this class for:
 * - Initial body placement (converting orbital elements to position/velocity)
 * - Trajectory planning (2-body approximations for maneuvers)
 * - Analysis (converting position/velocity to orbital elements for debugging)
 * Do NOT use this class for:
 * - Tracking current state (use position/velocity directly)
 * - Long-term position prediction in n-body systems (perturbations dominate)
 *
 * Generated by Claude (Sonnet 4.5) - Absolute Time Refactor
 */
public record Orbit(
        double semiMajorAxis,
        double eccentricity,
        double inclination,
        double ascendingNode,
        double periapsis,
        double trueAnomaly,
        Gravitational centerBody
) {

    // ==================== STATIC FACTORY METHODS ====================

    /**
     * Calculate orbital elements from instantaneous position and velocity.
     *
     * Result is only valid at this moment. In n-body systems, the actual
     * trajectory will immediately diverge from these elements.
     *
     * @param centerBody The gravitational body being orbited
     * @param position Current position vector
     * @param velocity Current velocity vector
     * @return Orbital elements describing the instantaneous orbit
     */
    public static Orbit fromState(Gravitational centerBody,
                                  Vector3D position,
                                  Vector3D velocity) {

        // Specific orbital energy
        double energy = velocity.magnitudeSquared() / 2.0 -
                centerBody.getGravitationalParameter() / position.magnitude();

        // Semi-major axis
        double semiMajorAxis = Math.abs(-centerBody.getGravitationalParameter() / (2.0 * energy));

        // Angular momentum vector
        Vector3D angularMomentum = position.cross(velocity);

        // Eccentricity vector
        Vector3D eccentricityVec = velocity
                .cross(angularMomentum)
                .divide(centerBody.getGravitationalParameter())
                .subtract(position.normalize());

        // Node vector (points to ascending node)
        Vector3D node = Vector3D.UNIT_Z.cross(angularMomentum);

        // Inclination (angle from reference plane)
        double inclination = Math.acos(angularMomentum.getZ() / angularMomentum.magnitude());

        // Longitude of ascending node
        double ascendingNode;
        if (node.magnitude() > 1e-10) {
            double omega = Math.acos(node.getX() / node.magnitude());
            ascendingNode = node.getY() < 0 ? 2 * Math.PI - omega : omega;
        } else {
            ascendingNode = 0.0; // Undefined for non-inclined orbits
        }

        // Argument of periapsis
        double argumentOfPeriapsis;
        if (node.magnitude() > 1e-10 && eccentricityVec.magnitude() > 1e-10) {
            double aop = Math.acos(node.dot(eccentricityVec) /
                    (node.magnitude() * eccentricityVec.magnitude()));
            argumentOfPeriapsis = eccentricityVec.getZ() < 0 ? 2 * Math.PI - aop : aop;
        } else {
            argumentOfPeriapsis = 0.0; // Undefined for circular or non-inclined orbits
        }

        // Project 3D position into 2D orbital plane to calculate true anomaly
        Vector3D positionIn2D = position.rotateInto2spaceFrom3space(
                ascendingNode,
                inclination,
                argumentOfPeriapsis
        );

        double trueAnomaly = Math.atan2(positionIn2D.getY(), positionIn2D.getX());
        trueAnomaly = wrapAngle(trueAnomaly);

        // Validation
        if (eccentricityVec.magnitude() < 0) {
            throw new IllegalArgumentException("Eccentricity cannot be negative: " + eccentricityVec);
        }
        if (semiMajorAxis <= 0) {
            throw new IllegalArgumentException("Semi-major axis must be positive: " + semiMajorAxis);
        }
        if (inclination < 0 || inclination > Math.PI) {
            throw new IllegalArgumentException("Inclination must be [0, π]: " + inclination);
        }

        return new Orbit(
                semiMajorAxis,
                eccentricityVec.magnitude(),
                inclination,
                ascendingNode,
                argumentOfPeriapsis,
                trueAnomaly,
                centerBody
        );
    }

    // ==================== STATE PROPAGATION (ABSOLUTE TIME) ====================

    /**
     * Calculate position and velocity at an absolute time in pure 2-body system.
     *
     * IMPORTANT: This uses the orbital elements stored in this record, which were
     * calculated at 'currentTime'. The prediction is only valid if:
     * 1. No significant perturbations from other bodies
     * 2. absoluteTime is close to currentTime (minutes to hours, not days)
     * 3. You're in a 2-body approximation scenario
     *
     * In n-body systems (like the actual simulation), actual position will diverge
     * from this prediction. Use this for trajectory planning, not position tracking.
     *
     * @param absoluteTime The simulation time to predict position for
     * @param currentTime The simulation time when this orbit was calculated
     * @return Predicted position and velocity (2-body approximation)
     * @throws IllegalArgumentException if absoluteTime < currentTime
     */
    public OrbitalState stateAt(double absoluteTime, double currentTime) {
        double timeElapsed = currentTime - absoluteTime;

        if (timeElapsed < 0) {
            throw new IllegalArgumentException(
                    String.format("Cannot predict past: absoluteTime=%.1f < currentTime=%.1f",
                            absoluteTime, currentTime)
            );
        }

        if (Math.abs(timeElapsed) < 1e-6) {
            // At current time - return state at the true anomaly this orbit was calculated from
            return calculateStateAtTrueAnomaly(trueAnomaly);
        }

        // Calculate mean anomaly at this time
        double meanAngularVelocity = Math.sqrt(centerBody.getGravitationalParameter() /
                Math.pow(semiMajorAxis, 3));
        double currentMeanAnomaly = meanAnomaly();
        double futureMeanAnomaly = wrapAngle(currentMeanAnomaly + meanAngularVelocity * timeElapsed);

        // Solve Kepler's equation
        double eccentricAnomaly = solveKeplersEquation(futureMeanAnomaly);

        // Convert to true anomaly
        double futureNu = eccentricToTrueAnomaly(eccentricAnomaly);
        futureNu = wrapAngle(futureNu);

        return calculateStateAtTrueAnomaly(futureNu);
    }

    /**
     * Calculate position and velocity at a specific true anomaly.
     */
    private OrbitalState calculateStateAtTrueAnomaly(double nu) {
        double gravitationalParameter = centerBody.getGravitationalParameter();

        // Calculate radius at true anomaly
        double semiLatusRectum = semiMajorAxis * (1.0 - eccentricity * eccentricity);
        double radius = semiLatusRectum / (1.0 + eccentricity * Math.cos(nu));

        // Position in 2D orbital plane
        Vector3D position2D = new Vector3D(
                radius * Math.cos(nu),
                radius * Math.sin(nu),
                0.0
        );

        // Velocity in 2D orbital plane
        double sqrtMuOverP = Math.sqrt(gravitationalParameter / semiLatusRectum);
        double radialVelocity = sqrtMuOverP * eccentricity * Math.sin(nu);
        double tangentialVelocity = sqrtMuOverP * (1.0 + eccentricity * Math.cos(nu));

        Vector3D velocity2D = new Vector3D(
                radialVelocity * Math.cos(nu) - tangentialVelocity * Math.sin(nu),
                radialVelocity * Math.sin(nu) + tangentialVelocity * Math.cos(nu),
                0.0
        );

        // Rotate to 3D space
        Vector3D position3D = position2D.rotateInto3spaceFrom2space(
                ascendingNode, inclination, periapsis
        );

        Vector3D velocity3D = velocity2D.rotateInto3spaceFrom2space(
                ascendingNode, inclination, periapsis
        );

        return new OrbitalState(position3D, velocity3D);
    }

    // ==================== ORBITAL GEOMETRY ====================

    public double semiMinorAxis() {
        return semiMajorAxis * Math.sqrt(1 - eccentricity * eccentricity);
    }

    public double orbitalPeriod() {
        return 2 * Math.PI * Math.sqrt(Math.pow(semiMajorAxis, 3) /
                centerBody.getGravitationalParameter());
    }

    public double calculateRadiusAtTrueAnomaly(double nu) {
        double semiLatusRectum = semiMajorAxis * (1.0 - eccentricity * eccentricity);
        return semiLatusRectum / (1.0 + eccentricity * Math.cos(nu));
    }

    public Vector3D periapsisPoint() {
        return calculatePositionAtTrueAnomaly(0.0);
    }

    public Vector3D apoapsisPoint() {
        return calculatePositionAtTrueAnomaly(Math.PI);
    }

    public Vector3D getAscendingNode() {
        if (Math.abs(inclination) > 1e-6) {
            return new Vector3D(
                    Math.cos(ascendingNode),
                    Math.sin(ascendingNode),
                    0.0
            ).multiply(calculateRadiusAtTrueAnomaly(-periapsis));
        } else {
            return Vector3D.ZERO;
        }
    }

    public Vector3D getDescendingNode() {
        if (Math.abs(inclination) > 1e-6) {
            return new Vector3D(
                    Math.cos(ascendingNode + Math.PI),
                    Math.sin(ascendingNode + Math.PI),
                    0.0
            ).multiply(calculateRadiusAtTrueAnomaly(Math.PI - periapsis));
        } else {
            return Vector3D.ZERO;
        }
    }

    public Vector3D calculatePositionAtTrueAnomaly(double nu) {
        double radius = calculateRadiusAtTrueAnomaly(nu);
        return new Vector3D(
                radius * Math.cos(nu),
                radius * Math.sin(nu),
                0.0
        ).rotateInto3spaceFrom2space(ascendingNode, inclination, periapsis);
    }

    public Vector3D calculateVelocityAtPosition(Vector3D position) {
        // Find true anomaly at this position
        Vector3D flattenedOrbit = position.rotateInto2spaceFrom3space(
                ascendingNode, inclination, periapsis);
        double nu = Math.atan2(flattenedOrbit.getY(), flattenedOrbit.getX());

        // Calculate velocity at this true anomaly
        double mu = centerBody.getGravitationalParameter();
        double h = Math.sqrt(mu * semiMajorAxis * (1.0 - eccentricity * eccentricity));

        double radialVel = (mu / h) * eccentricity * Math.sin(nu);
        double tangentialVel = (mu / h) * (1.0 + eccentricity * Math.cos(nu));

        return new Vector3D(
                radialVel * Math.cos(nu) - tangentialVel * Math.sin(nu),
                radialVel * Math.sin(nu) + tangentialVel * Math.cos(nu),
                0.0
        ).rotateInto3spaceFrom2space(ascendingNode, inclination, periapsis);
    }

    public double calculateTimeToPoint(Vector3D targetPoint) {
        Vector3D flattenedOrbit = targetPoint.rotateInto2spaceFrom3space(
                ascendingNode, inclination, periapsis);
        double targetNu = Math.atan2(flattenedOrbit.getY(), flattenedOrbit.getX());

        double E_current = trueToEccentricAnomaly(trueAnomaly);
        double E_target = trueToEccentricAnomaly(targetNu);

        double M_current = E_current - eccentricity * Math.sin(E_current);
        double M_target = E_target - eccentricity * Math.sin(E_target);

        double meanAngularVel = Math.sqrt(centerBody.getGravitationalParameter() /
                Math.pow(semiMajorAxis, 3));

        return wrapAngle(M_target - M_current) / meanAngularVel;
    }

    public Vector3D rotationVector() {
        return new Vector3D(ascendingNode, inclination, periapsis);
    }

    // ==================== ANOMALY CONVERSIONS ====================

    public double meanAnomaly() {
        double E = trueToEccentricAnomaly(trueAnomaly);
        return E - eccentricity * Math.sin(E);
    }

    public double eccentricToTrueAnomaly(double E) {
        double semiMinorRatio = Math.sqrt(1 - eccentricity * eccentricity);
        return Math.atan2(
                semiMinorRatio * Math.sin(E) / (1 - eccentricity * Math.cos(E)),
                (Math.cos(E) - eccentricity) / (1 - eccentricity * Math.cos(E))
        );
    }

    public double trueToEccentricAnomaly(double nu) {
        double semiMinorRatio = Math.sqrt(1 - eccentricity * eccentricity);
        double radiusRatio = 1 + eccentricity * Math.cos(nu);

        double anomaly = semiMinorRatio * Math.sin(nu) / radiusRatio;
        return Math.atan2(
                wrapAngle(anomaly),
                (eccentricity + Math.cos(nu)) / radiusRatio
        );
    }

    private double solveKeplersEquation(double M) {
        double E = M; // Initial guess
        double tolerance = 1e-8;
        int maxIterations = 100;

        for (int i = 0; i < maxIterations; i++) {
            double f = E - eccentricity * Math.sin(E) - M;
            double fPrime = 1 - eccentricity * Math.cos(E);
            double deltaE = f / fPrime;
            E -= deltaE;

            if (Math.abs(deltaE) < tolerance) {
                break;
            }
        }

        return E;
    }

    // ==================== UTILITY METHODS ====================

    public static double wrapAngle(double angle) {
        double normalized = angle % (2 * Math.PI);
        return normalized < 0 ? normalized + (2 * Math.PI) : normalized;
    }

    public boolean canUseHohmann(Orbit target) {
        if (centerBody != target.centerBody()) {
            return false;
        }
        if (eccentricity > 0.1 || target.eccentricity() > 0.1) {
            return false;
        }
        double inclinationDiff = Math.abs(inclination - target.inclination());
        return inclinationDiff < Math.toRadians(5.0);
    }
}