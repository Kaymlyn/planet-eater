package com.kaymlyn.planeteater.simulation.physics;

import com.kaymlyn.planeteater.simulation.celestial.OrbitalSystem;
import com.kaymlyn.planeteater.simulation.celestial.Orbiter;
import com.kaymlyn.planeteater.simulation.vehicles.Spacecraft;
import lombok.Getter;
import lombok.Setter;
import lombok.ToString;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/**
 * Enhanced flight plan for spacecraft orbital transfers
 *
 * Represents a complete sequence of maneuvers from origin to destination.
 * Tracks feasibility, delta-V requirements, and generates telemetry for rendering.
 *
 * Note: This class handles delta-V calculations only. Fuel requirements are
 * calculated by the Vehicle based on its specific characteristics (exhaust velocity, mass).
 *
 * Generated by Claude (Sonnet 4.5)
 */
@ToString
public class Itinerary {
    private final List<PiecewiseState> telemetry;

    @Getter
    private final double startTime;

    @Getter
    private ManeuverDetails initialManeuver;

    @Setter
    @Getter
    private Orbiter finalDestination;

    @Setter
    @Getter
    private Spacecraft.SpacecraftState finalSpacecraftState;

    // Feasibility tracking
    @Getter
    private boolean feasible;

    @Getter
    private String infeasibilityReason;

    /**
     * -- SETTER --
     *  Set the launch delta-V requirement
     *  This is the delta-V needed to escape the departure body's gravity well
     */
    // Delta-V breakdown (not fuel - that's vehicle-specific)
    @Setter
    @Getter
    private double launchDeltaV;

    /**
     * -- SETTER --
     *  Set the landing delta-V requirement
     *  This is the delta-V needed to land on the destination body
     */
    @Setter
    @Getter
    private double landingDeltaV;

    @Getter
    private double travelDeltaV;

    @Getter
    private double totalWaitTime;

    public Itinerary(double startTime) {
        this.startTime = startTime;
        this.telemetry = new ArrayList<>();
        this.feasible = true;
        this.infeasibilityReason = null;
        this.launchDeltaV = 0.0;
        this.landingDeltaV = 0.0;
        this.travelDeltaV = 0.0;
        this.totalWaitTime = 0.0;
    }

    public void setInitialManeuver(ManeuverDetails initialManeuver) {
        this.initialManeuver = initialManeuver;
        launchDeltaV = initialManeuver.getDeltaV();

    }

    /**
     * Mark this itinerary as infeasible
     */
    public void setInfeasible(String reason) {
        this.feasible = false;
        this.infeasibilityReason = reason;
    }

    /**
     * SIMPLIFIED telemetry generation for burn+coast model.
     *
     * No more epoch issues - each coast creates its own orbit.
     * No more zero-state maneuvers - burns always generate 1 state.
     *
     * Generated by Claude (Sonnet 4.5)
     */
    public List<PiecewiseState> generateTelemetry(OrbitalSystem system) {
        if (!telemetry.isEmpty() || !feasible) {
            return telemetry;
        }

        ManeuverDetails current = initialManeuver;

        while (current != null) {
            String id = current.getId();

            // Determine maneuver type from ID
            boolean isBurn = id.contains("Burn") ||
                    id.contains("Launch") ||
                    id.contains("Detach");

            if (isBurn) {
                // Burns: Single state at completion
                telemetry.add(new PiecewiseState(
                        current.getId(),
                        current.getEndingPosition(),
                        current.getEndingVelocity(),
                        current.getTimeToExecute(),
                        1.0  // 100% complete
                ));

            } else {  // Coast
                // Generate states at timestep intervals
                int steps = (int) (current.getTimeToExecute() / system.getTimeStep());

                // Always generate at least 1 state
                if (steps == 0) {
                    steps = 1;
                }

                for (int step = 0; step < steps; step++) {
                    double t = step * system.getTimeStep();

                    // Propagate orbit from maneuver start
                    // Orbit was created at burn completion, so epoch is correct
                    OrbitalState state = current.getOrbit()
                            .calculateOrbitAfterT0(t);

                    telemetry.add(new PiecewiseState(
                            current.getId() + " @t+" + t,
                            state.position(),
                            state.velocity(),
                            t,
                            t / current.getTimeToExecute()
                    ));
                }
            }

            current = current.getNext();
        }

        return telemetry;
    }

    /**
     * Get total flight time (sum of all maneuver durations)
     */
    public double getTotalFlightTime() {
        ManeuverDetails details = initialManeuver;
        double counter = 0.0;
        while (details != null) {
            counter += details.getTimeToExecute();
            details = details.getNext();
        }
        return  counter;
    }

    /**
     * Validate this itinerary against spacecraft capabilities
     *
     * @param spacecraft The spacecraft that will execute this itinerary
     * @return true if spacecraft can execute this plan, false otherwise
     */
    public boolean validateAgainstSpacecraft(Spacecraft spacecraft) {
        if (!feasible) {
            return false;
        }

        // Check if spacecraft has enough delta-V capability
        double requiredDeltaV = travelDeltaV + launchDeltaV + landingDeltaV;
        double availableDeltaV = spacecraft.getAvailableDeltaV();

        if (availableDeltaV < requiredDeltaV) {
            setInfeasible(String.format(
                "Insufficient delta-V: required %.1f m/s, available %.1f m/s",
                requiredDeltaV, availableDeltaV
            ));
            return false;
        }

        // Check fuel requirements
        double requiredFuel = spacecraft.fuelRequired(requiredDeltaV);
        if (requiredFuel > spacecraft.getFuelMass()) {
            setInfeasible(String.format(
                "Insufficient fuel: required %.1f kg, available %.1f kg",
                requiredFuel, spacecraft.getFuelMass()
            ));
            return false;
        }

        return true;
    }

    /**
     * Create a summary string of this itinerary
     */
    public String getSummary() {
        StringBuilder sb = new StringBuilder();
        sb.append("=== ITINERARY ===\n");
        sb.append(String.format("Start Time: %.2f days\n", startTime / PhysicsConstants.SECONDS_PER_DAY));
        sb.append(String.format("Feasible: %s\n", feasible ? "YES" : "NO - " + infeasibilityReason));

        if (feasible) {
//            sb.append(String.format("Maneuvers: %d\n", maneuvers.size()));
            sb.append(String.format("Total Δv: %.1f m/s\n", travelDeltaV));
            sb.append(String.format("  Launch: %.1f m/s\n", launchDeltaV));
            sb.append(String.format("  Landing: %.1f m/s\n", landingDeltaV));
            sb.append(String.format("Total Time: %.2f days\n",
                getTotalFlightTime() / PhysicsConstants.SECONDS_PER_DAY));

            if (totalWaitTime > 0) {
                sb.append(String.format("Wait Time: %.2f days\n",
                    totalWaitTime / PhysicsConstants.SECONDS_PER_DAY));
            }

            sb.append(String.format("Destination: %s (%s)\n",
                finalDestination != null ? finalDestination.getId() : "None",
                finalSpacecraftState != null ? finalSpacecraftState : "Unknown"));
        }

        return sb.toString();
    }
}
