    /**
     * Start the operation (launch from platform)
     */
    public boolean launch(Spacecraft spacecraft, double currentTime) {
        if (status != OperationStatus.PLANNING) {
            return false;
        }
        
        // Consume fuel for outbound journey
        spacecraft.consumeFuel(outboundTrajectory.fuelRequired);
        spacecraft.setState(Spacecraft.SpacecraftState.TRAVELING);
        status = OperationStatus.TRAVELING;
        startTime = currentTime;
        
        return true;
    }

    public void deploy() {
        status = OperationStatus.DEPLOYING;

    }
    
    /**
     * Update the operation - progress mining, handle travel, etc.
     */
    public void update(double currentTime, double dt) {
        switch (status) {
            case PLANNING, COMPLETED -> {
            }
            case TRAVELING -> {
                // Check if arrived at asteroid
                double travelElapsed = currentTime - startTime;
                if (travelElapsed >= outboundTrajectory.travelTime) {
                    arriveAtDestination(currentTime);
                }
            }
            case ACTIVE ->
                    performTask(dt);
            case DEPLOYING -> {
                double deployElapsed = currentTime - startTime;
                if (deployElapsed >= deploymentTime) {
                    status = OperationStatus.ACTIVE;
                }
            }
            case DECAMP -> {
                double timeElapsed = currentTime - startTime;
                if (timeElapsed >= deploymentTime/2) {
                    //incomplete. send the ship to the orbital platform
                    status = OperationStatus.COMPLETED;
                }
            }
        }
    }
    
    /**
     * Arrive at the asteroid and begin mining
     */
    private void arriveAtDestination(double currentTime) {
        spacecraft.setState(Spacecraft.SpacecraftState.AT_ASTEROID);
        status = OperationStatus.DEPLOYING;
        startTime = currentTime;
        
        // Disembark miners
        for (MiningEntity miner : miners) {
            spacecraft.disembarkEntity(miner);
            miner.setState(MiningEntity.EntityState.MINING);
            miner.setCurrentLocation(target.getId());
        }
    }

    /**
     * Begin return journey to platform
     */
    private void beginReturn(OrbitalPlatform platform) {
        // Re-board miners
        for (MiningEntity miner : miners) {
            spacecraft.boardEntity(miner);
            miner.setCurrentLocation(null);
        }

        // Consume fuel for return
        outboundTrajectory = TravelCalculator.calculateRendezvous(
                platform.getPosition(),
                platform.getVelocity(),
                target,
                system.getCurrentTime(),
                spacecraft,
                system
        );

        spacecraft.consumeFuel(returnTrajectory.fuelRequired);
        spacecraft.setState(Spacecraft.SpacecraftState.RETURNING);
        startTime = System.currentTimeMillis() / 1000.0; // Use real time for simplicity
    }

