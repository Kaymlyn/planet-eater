/**
 * REFACTORED: CentralMind using state, not orbits
 *
 * Orbital platform/base of operations.
 * Position and velocity are ground truth.
 *
 * Generated by Claude (Sonnet 4.5) - Architecture Refactor
 */
@Data
public class CentralMind extends Vehicle implements Orbiter, Satellite, Dockable {

    private Gravitational parentBody;
    private OrbitalSystem system;
    private Map<String, Spacecraft> hanger;
    // Position and velocity owned by Spacecraft (not inherited from Vehicle)
    private Vector3D position;
    private Vector3D velocity;

    public CentralMind(String id, OrbitalSystem system) {
        super(id, new Composition(), 1e4, 1e3, 2, true, 12, 0);
        this.system = system;
        this.crew = new ArrayList<>();
        this.hanger = new HashMap<>();
        Composition construction = new Composition();
        construction.addMaterialAsVolume(Material.IRON,10);
        construction.addMaterialAsVolume(Material.ALUMINUM, 20);
        construction.addMaterialAsVolume(Material.TITANIUM, 40);
        this.getConstruction().addBulkMaterial(construction);
        system.placeInCircularOrbit(this, PhysicsConstants.AU,Math.PI);
    }

    @Override
    public double getMass() {
        return getConstruction().getTotalMass() + getFuelMass() +
                crew.stream().mapToDouble(Automaton::getMass).reduce(0.0, Double::sum);
    }

    @Override
    public String toString() {
        return String.format("OrbitalPlatform[id=%s, position=%s, crew=%s",
                id, position, crew);
    }

    public void update(Vector3D acceleration, double dt) {
        this.setVelocity(getVelocity().add(acceleration.multiply(dt)));
        this.setPosition(getPosition().add(getVelocity().multiply(dt)));
    }

    @Override
    public void setParentBody(Gravitational parentBody) {
        this.parentBody = parentBody;
    }

    @Override
    public OrbitalSystem getSystem() {
        return system;
    }

    public boolean equals(final Object o) {
        return o == this
                || o instanceof CentralMind other
                && other.canEqual(this)
                && Objects.equals(this.getParentBody(), other.getParentBody());
    }

    protected boolean canEqual(final Object other) {
        return other instanceof CentralMind;
    }

    public int hashCode() {
        int result = 1;
        result = result * 59 + (this.getParentBody() == null ? 43 : this.getParentBody().hashCode());
        result = result * 59 + (this.getId() == null ? 43 : this.getId().hashCode());
        return result;
    }

    @Override
    public Map<String, Spacecraft> getHanger() {
        return hanger;
    }

    @Override
    public void dock(Spacecraft spacecraft) {
        hanger.put(spacecraft.getId(), spacecraft);
        spacecraft.setPosition(this.position);
        spacecraft.setVelocity(this.velocity);
        spacecraft.setOrbiting(this);
    }

    @Override
    public void updateDocked() {
        hanger.forEach((id,ship) -> {ship.setPosition(this.position); ship.setVelocity(this.velocity);});
    }
}