package com.kaymlyn.planeteater.simulation.vehicles;

import com.kaymlyn.planeteater.simulation.entities.Automaton;
import com.kaymlyn.planeteater.simulation.operations.Operation;
import com.kaymlyn.planeteater.simulation.physics.Vector3D;
import com.kaymlyn.planeteater.simulation.resources.Composition;
import com.kaymlyn.planeteater.simulation.resources.Material;
import lombok.Getter;
import lombok.Setter;

import java.util.List;
import java.util.Map;

/**
 * Represents a spacecraft for traveling between celestial bodies
 * Can carry cargo and mining entities
 * Recyclable - can be dismantled for materials
 * 
 * Generated by Claude (Sonnet 4.5)
 */
@Getter
@Setter
public class Spacecraft extends Vehicle {
    
    public enum SpacecraftState {
        DOCKED,         // At platform
        TRAVELING,      // In transit
        STRANDED
    }
    private Composition construction;   // Materials used to build the spacecraft
    private Composition cargo;
    private List<Automaton> crew;

    private SpacecraftState state;
    private String destination;          // ID of destination body
    
    public Spacecraft(String id, double dryMass, double maxFuelCapacity, 
                     double cargoCapacity, double exhaustVelocity, 
                     boolean hasLifeSupport, int maxCrewCapacity) {
        super(id, dryMass, maxFuelCapacity, cargoCapacity, exhaustVelocity, hasLifeSupport, maxCrewCapacity);
        this.id = id;

        this.construction = new Composition();
        this.state = SpacecraftState.DOCKED;
    }

    public void commenceOperation(Operation operation) {
        operation.deploy();
    }
    
    /**
     * Create a basic cargo shuttle (no life support)
     */
    public static Spacecraft createCargoShuttle(String id) {
        Spacecraft ship = new Spacecraft(id, 2000.0, 5000.0, 10000.0, 3000.0, false, 0);
        
        // Construction materials
        ship.construction.addMaterialAsVolume(Material.ALUMINUM, 1200.0);
        ship.construction.addMaterialAsVolume(Material.TITANIUM, 500.0);
        ship.construction.addMaterialAsVolume(Material.IRON, 300.0);
        
        return ship;
    }

    /**
     * Recycle the spacecraft, returning all construction materials
     */
    public Composition recycle() {
        Composition materials = new Composition();
        
        // Return all construction materials
        for (Map.Entry<Material, Double> entry : construction.getMaterials().entrySet()) {
            materials.addMaterialAsVolume(entry.getKey(), entry.getValue());
        }
        
        // Return any remaining fuel (assuming it's a recyclable type)
        // In practice, fuel might be hydrogen or similar
        return materials;
    }
    
    @Override
    public String toString() {
        return String.format("com.kaymlyn.planeteater.vehicles.Spacecraft[id=%s, state=%s, mass=%.1f kg, fuel=%.1f/%.1f kg, " +
            "cargo=%.1f/%.1f kg, crew=%d/%d, deltaV=%.1f m/s]",
            id, state, getTotalMass(), fuelMass, maxFuelCapacity,
            cargo.getTotalMass(), cargoCapacity, crew.size(), maxCrewCapacity,
            getAvailableDeltaV());
    }
}