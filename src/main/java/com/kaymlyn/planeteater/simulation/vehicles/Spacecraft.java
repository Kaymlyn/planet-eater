/**
 * Represents a spacecraft for traveling between celestial bodies
 * Can carry cargo and mining entities
 * Recyclable - can be dismantled for materials
 * 
 * Generated by Claude (Sonnet 4.5)
 */
@EqualsAndHashCode(callSuper = false)
@Data
public class Spacecraft extends Vehicle {

    public enum SpacecraftState {
        DOCKED,         // At platform
        TRAVELING,      // In transit
        ORBITING,
        STRANDED
    }

    private Composition construction;   // Materials used to build the spacecraft
    private Composition cargo;
    private List<Automaton> crew;

    private SpacecraftState state;
    private Orbiter orbiting;
    private Itinerary itinerary;
    private List<PiecewiseState> telemetry;
    private int currentTravelCycle;
    private double transitTime;

    private OrbitalSystem system;

    public Spacecraft(String id,
                      double dryMass,
                      double maxFuelCapacity,
                      double cargoCapacity,
                      double exhaustVelocity,
                      boolean hasLifeSupport,
                      int maxCrewCapacity,
                      int minCrewRequirement,
                      Orbiter shipyard) {
        super(id, dryMass, maxFuelCapacity, cargoCapacity, exhaustVelocity, hasLifeSupport, maxCrewCapacity, minCrewRequirement);

        this.construction = new Composition();
        this.state = SpacecraftState.DOCKED;
        this.itinerary = null;
        this.telemetry = null;
        this.orbiting = shipyard;
        this.system = shipyard.getParentBody().getSystem();
        this.position = shipyard.getPosition();
        this.currentTravelCycle = 0;
        this.cargo = new Composition();
        this.crew = new ArrayList<>();

    }

    public Gravitational getLocation() {
        if(orbiting == null || !(orbiting instanceof Gravitational)) {
            return system.getCentralStar();
        } else {
            return ((Gravitational) orbiting);
        }
    }

    public void programItinerary(Itinerary itinerary){
        this.itinerary = itinerary;
        currentTravelCycle = 0;
    }

    public boolean launch() {
        if (itinerary == null) {
            return false;
        }

        // Validate itinerary is feasible
        if (!itinerary.isFeasible()) {
            System.out.println("Cannot launch: " + itinerary.getInfeasibilityReason());
            return false;
        }

        // Check fuel availability
        double requiredFuel = fuelRequired(
                itinerary.getTravelDeltaV() +
                        itinerary.getLaunchDeltaV() +
                        itinerary.getLandingDeltaV());

        if (requiredFuel > fuelMass) {
            System.out.println("Cannot launch: insufficient fuel");
            return false;
        }

        // First launch cycle - consume launch fuel and register with system
        if (currentTravelCycle == 0) {
            double launchFuel = fuelRequired(itinerary.getLaunchDeltaV());
            consumeFuel(launchFuel);
            this.state = SpacecraftState.ORBITING;
            system.register(this);
        }

        return true;
    }

    public void completeTravel() {
        if (itinerary == null) {
            return;
        }

        // Consume landing fuel if applicable
        double landingFuel = fuelRequired(itinerary.getLandingDeltaV());
        consumeFuel(landingFuel);

        // Clear telemetry cache
        telemetry = null;

        // Update spacecraft state based on destination type
        Spacecraft.SpacecraftState targetState = itinerary.getFinalSpacecraftState();

        if(targetState == SpacecraftState.DOCKED) {
            if(orbiting instanceof Dockable) {
                setState(SpacecraftState.DOCKED);
                system.unregister(this);
            } else if (orbiting instanceof Gravitational) {
                setState(SpacecraftState.ORBITING);
            } else {
                setState(SpacecraftState.STRANDED);
            }
        } else if (targetState == SpacecraftState.ORBITING) {
            if(orbiting instanceof Gravitational) {
                setState(SpacecraftState.ORBITING);
            } else if (orbiting instanceof Dockable) {
                setState(SpacecraftState.DOCKED);
                system.unregister(this);
            } else {
                setState(SpacecraftState.STRANDED);
            }
        } else {
            setState(SpacecraftState.STRANDED);
        }

        // Clear itinerary
        itinerary = null;
    }

    public void simulateTravel() {
        if(itinerary != null) {
            if(telemetry == null) {
                telemetry = itinerary.generateTelemetry(system);
            }
            if(telemetry == null) {
                return;
            }

            //Step through Telemetry based on
            if(telemetry.size() > currentTravelCycle) {
                position = telemetry.get(currentTravelCycle).position();
                if(!Double.isNaN(position.getZ())) {
                    this.state = SpacecraftState.TRAVELING;
                }
                currentTravelCycle++;
            } else {
                //Arrive at destination
                Vector3D finalPosition = null;
                if(itinerary.getFinalDestination() != null) {
                    this.orbiting = itinerary.getFinalDestination();
                    if(itinerary.getFinalSpacecraftState() == SpacecraftState.DOCKED) {
                        finalPosition = this.orbiting.getPosition();
                    } else {
                        finalPosition = telemetry.getLast().position();
                    }
                }

                if(finalPosition == null && !telemetry.isEmpty()) {
                    finalPosition = telemetry.getLast().position();
                } else {
                    finalPosition = position;
                }
                position = finalPosition;
                completeTravel();
            }
        }
    }

    //Calculate a dry run of the route
    public Itinerary planRoute(@NonNull Orbiter destination, boolean land, double maneuverStart, TransferOptimizer.OptimizationGoal priority) {
        Itinerary plannedRoute = Objects.requireNonNull(
                TransferOptimizer.selectBestTransfer(TransferOptimizer.generateTransferOptions(this, this.orbiting, destination, land, maneuverStart),
                Objects.requireNonNullElse(priority, TransferOptimizer.OptimizationGoal.MINIMUM_DELTAV))).getItinerary();

        return plannedRoute;
    }


    /**
     * Recycle the spacecraft, returning all construction materials
     */
    public Composition recycle() {
        Composition materials = new Composition();
        
        // Return all construction materials
        for (Map.Entry<Material, Double> entry : construction.getMaterials().entrySet()) {
            materials.addMaterialAsVolume(entry.getKey(), entry.getValue());
        }
        
        // Return any remaining fuel (assuming it's a recyclable type)
        // In practice, fuel might be hydrogen or similar
        system.unregister(this);
        return materials;
    }
    
    @Override
    public String toString() {
        return String.format("com.kaymlyn.planeteater.vehicles.Spacecraft[id=%s, state=%s, mass=%.1f kg, fuel=%.1f/%.1f kg, " +
            "cargo=%.1f/%.1f kg, crew=%d/%d, deltaV=%.1f m/s]",
            id, state, getTotalMass(), fuelMass, maxFuelCapacity,
            cargo.getTotalMass(), cargoCapacity, crew.size(), maxCrewCapacity,
            getAvailableDeltaV());
    }

    /* inclination cross over
     * orbit 1 x orbit 2
     * when z1 = z2
     */
}