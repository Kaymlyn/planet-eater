/**
 * REFACTORED: Spacecraft using absolute time-based telemetry lookup
 *
 * KEY CHANGE: Removed iterator pattern (currentTravelCycle counter).
 * Position is now queried by absolute simulation time, not array index.
 *
 * Position and velocity are ground truth.
 * Itinerary stores predicted trajectory states with absolute timestamps.
 *
 * Generated by Claude (Sonnet 4.5) - Absolute Time Refactor
 */
@EqualsAndHashCode(callSuper = false)
@Data
public class Spacecraft extends Vehicle {

    public enum SpacecraftState {
        DOCKED,
        TRAVELING,
        ORBITING,
        STRANDED
    }

    private Composition construction;
    private Composition cargo;
    private List<Automaton> crew;

    private SpacecraftState state;
    private Orbiter orbiting;
    private Itinerary itinerary;
    private List<PiecewiseState> telemetry;

    // REMOVED: private int currentTravelCycle;  // No longer needed!

    private double transitTime;

    private OrbitalSystem system;

    public Spacecraft(String id,
                      double dryMass,
                      double maxFuelCapacity,
                      double cargoCapacity,
                      double exhaustVelocity,
                      boolean hasLifeSupport,
                      int maxCrewCapacity,
                      int minCrewRequirement,
                      Orbiter shipyard) {
        super(id, dryMass, maxFuelCapacity, cargoCapacity, exhaustVelocity,
                hasLifeSupport, maxCrewCapacity, minCrewRequirement);

        this.construction = new Composition();
        this.state = SpacecraftState.DOCKED;
        this.itinerary = null;
        this.telemetry = null;
        this.orbiting = shipyard;
        this.system = shipyard.getParentBody().getSystem();
        this.position = shipyard.getPosition();
        // REMOVED: this.currentTravelCycle = 0;
        this.cargo = new Composition();
        this.crew = new ArrayList<>();
    }

    public Gravitational getLocation() {
        if (orbiting == null || !(orbiting instanceof Gravitational)) {
            return system.getCentralStar();
        } else {
            return (Gravitational) orbiting;
        }
    }

    public void programItinerary(Itinerary itinerary) {
        this.itinerary = itinerary;
        // REMOVED: currentTravelCycle = 0;  // No longer needed
    }

    public boolean launch() {
        if (itinerary == null) {
            return false;
        }

        if (!itinerary.isFeasible()) {
            System.out.println("Cannot launch: " + itinerary.getInfeasibilityReason());
            return false;
        }

        double requiredFuel = fuelRequired(
                itinerary.getTravelDeltaV() +
                        itinerary.getLaunchDeltaV() +
                        itinerary.getLandingDeltaV());

        if (requiredFuel > fuelMass) {
            System.out.println("Cannot launch: insufficient fuel");
            return false;
        }

        // Launch happens once - consume fuel and change state
        double launchFuel = fuelRequired(itinerary.getLaunchDeltaV());
        consumeFuel(launchFuel);
        this.state = SpacecraftState.ORBITING;
        system.register(this);

        return true;
    }

    public void completeTravel() {
        if (itinerary == null) {
            return;
        }

        double landingFuel = fuelRequired(itinerary.getLandingDeltaV());
        consumeFuel(landingFuel);

        telemetry = null;

        SpacecraftState targetState = itinerary.getFinalSpacecraftState();

        if (targetState == SpacecraftState.DOCKED) {
            if (orbiting instanceof Dockable) {
                setState(SpacecraftState.DOCKED);
                system.unregister(this);
            } else if (orbiting instanceof Gravitational) {
                setState(SpacecraftState.ORBITING);
            } else {
                setState(SpacecraftState.STRANDED);
            }
        } else if (targetState == SpacecraftState.ORBITING) {
            if (orbiting instanceof Gravitational) {
                setState(SpacecraftState.ORBITING);
            } else if (orbiting instanceof Dockable) {
                setState(SpacecraftState.DOCKED);
                system.unregister(this);
            } else {
                setState(SpacecraftState.STRANDED);
            }
        } else {
            setState(SpacecraftState.STRANDED);
        }

        itinerary = null;
    }

    /**
     * REFACTORED: Time-based position lookup instead of array iteration
     *
     * OLD APPROACH: Increment currentTravelCycle counter, sync with system steps
     * NEW APPROACH: Query telemetry for state at current simulation time
     *
     * Benefits:
     * - No synchronization bugs
     * - Can query position at any time
     * - Simpler save/load (just save system time)
     * - More robust to variable time steps
     */
    public void simulateTravel() {
        if (itinerary == null) {
            return;
        }

        // Generate telemetry on first call (lazy initialization)
        if (telemetry == null) {
            telemetry = itinerary.generateTelemetry(system);
        }

        if (telemetry == null || telemetry.isEmpty()) {
            return;
        }

        // NEW: Query position by absolute simulation time
        double currentTime = system.getCurrentTime();
        PiecewiseState currentState = findStateAt(currentTime);

        if (currentState != null) {
            position = currentState.position();

            if (!Double.isNaN(position.getZ())) {
                this.state = SpacecraftState.TRAVELING;
            }
        }

        // Check if we've reached the end of the itinerary
        PiecewiseState lastState = telemetry.get(telemetry.size() - 1);
        if (currentTime >= lastState.absoluteTime()) {  // TODO: Will be renamed to absoluteTime in Phase 5
            // Arrive at destination
            Vector3D finalPosition;
            if (itinerary.getFinalDestination() != null) {
                this.orbiting = itinerary.getFinalDestination();
                if (itinerary.getFinalSpacecraftState() == SpacecraftState.DOCKED) {
                    finalPosition = this.orbiting.getPosition();
                } else {
                    finalPosition = lastState.position();
                }
            } else {
                finalPosition = lastState.position();
            }

            position = finalPosition;
            completeTravel();
        }
    }

    /**
     * Uses binary search for efficiency (O(log n) instead of O(n)).
     * Falls back to nearest state if exact match not found.
     *
     * @param absoluteTime The simulation time to query
     * @return The telemetry state closest to that time, or null if no telemetry
     */
    private PiecewiseState findStateAt(double absoluteTime) {
        if (telemetry == null || telemetry.isEmpty()) {
            return null;
        }

        // Edge cases
        if (absoluteTime <= telemetry.get(0).absoluteTime()) {  // TODO: Will be absoluteTime in Phase 5
            return telemetry.get(0);
        }

        PiecewiseState lastState = telemetry.get(telemetry.size() - 1);
        if (absoluteTime >= lastState.absoluteTime()) {
            return lastState;
        }

        // Binary search for closest state
        int left = 0;
        int right = telemetry.size() - 1;

        while (left <= right) {
            int mid = left + (right - left) / 2;
            PiecewiseState midState = telemetry.get(mid);
            double midTime = midState.absoluteTime();  // TODO: Will be absoluteTime in Phase 5

            if (Math.abs(midTime - absoluteTime) < 1e-6) {
                // Found exact match (within tolerance)
                return midState;
            }

            if (midTime < absoluteTime) {
                left = mid + 1;
            } else {
                right = mid - 1;
            }
        }

        // Return closest state (left is the first state after absoluteTime)
        if (left >= telemetry.size()) {
            return telemetry.get(telemetry.size() - 1);
        }

        if (left == 0) {
            return telemetry.get(0);
        }

        // Choose between left and left-1 based on which is closer
        PiecewiseState beforeState = telemetry.get(left - 1);
        PiecewiseState afterState = telemetry.get(left);

        double distBefore = Math.abs(beforeState.absoluteTime() - absoluteTime);
        double distAfter = Math.abs(afterState.absoluteTime() - absoluteTime);

        return distBefore < distAfter ? beforeState : afterState;
    }

    /**
     * NEW: Query spacecraft position at any absolute simulation time
     *
     * Useful for:
     * - Visualization/rendering at arbitrary frames
     * - Collision detection
     * - Mission analysis
     * - Debugging ("where was the spacecraft at T=5000?")
     *
     * @param absoluteTime The simulation time to query
     * @return Position at that time, or current position if no telemetry
     */
    public Vector3D getPositionAt(double absoluteTime) {
        if (telemetry == null || telemetry.isEmpty()) {
            return position;  // No telemetry, return current position
        }

        PiecewiseState state = findStateAt(absoluteTime);
        return state != null ? state.position() : position;
    }

    /**
     * NEW: Query spacecraft velocity at any absolute simulation time
     *
     * @param absoluteTime The simulation time to query
     * @return Velocity at that time, or current velocity if no telemetry
     */
    public Vector3D getVelocityAt(double absoluteTime) {
        if (telemetry == null || telemetry.isEmpty()) {
            return velocity;
        }

        PiecewiseState state = findStateAt(absoluteTime);
        return state != null ? state.velocity() : velocity;
    }

    public Itinerary planRoute(@NonNull Orbiter destination, boolean land,
                               double maneuverStart, TransferOptimizer.OptimizationGoal priority) {

        List<TransferOptimizer.TransferOption> options = TransferOptimizer.generateTransferOptions(
                this, this.orbiting, destination, land, maneuverStart);

        TransferOptimizer.TransferOption transferOptions = TransferOptimizer.selectBestTransfer(
                options,
                Objects.requireNonNullElse(priority, TransferOptimizer.OptimizationGoal.MINIMUM_DELTAV)
        );

        if (transferOptions == null) {
            return null;
        } else {
            return transferOptions.getItinerary();
        }
    }

    public Composition recycle() {
        Composition materials = new Composition();

        for (Map.Entry<Material, Double> entry : construction.getMaterials().entrySet()) {
            materials.addMaterialAsVolume(entry.getKey(), entry.getValue());
        }

        system.unregister(this);
        return materials;
    }

    @Override
    public String toString() {
        return String.format("Spacecraft[id=%s, state=%s, mass=%.1f kg, fuel=%.1f/%.1f kg, " +
                        "cargo=%.1f/%.1f kg, crew=%d/%d, deltaV=%.1f m/s]",
                id, state, getTotalMass(), fuelMass, maxFuelCapacity,
                cargo.getTotalMass(), cargoCapacity, crew.size(), maxCrewCapacity,
                getAvailableDeltaV());
    }
}