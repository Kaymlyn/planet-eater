    /**
     * Check if a position is near a Lagrange point (within given tolerance)
     */
    public static String findNearestLagrangePoint(Vector3D position,
                                                  Map<String, Vector3D> lagrangePoints,
                                                  double tolerance) {
        String nearest = null;
        double minDistance = Double.POSITIVE_INFINITY;

        for (Map.Entry<String, Vector3D> entry : lagrangePoints.entrySet()) {
            double distance = position.distanceTo(entry.getValue());
            if (distance < tolerance && distance < minDistance) {
                minDistance = distance;
                nearest = entry.getKey();
            }
        }

        return nearest;
    }

    public static Orbit generateRandomOrbitInitializer(double minimumAURadius,
                                                       double maximumAURadius,
                                                       double maximumEccentricity,
                                                       double maxInclination,
                                                       boolean prograde,
                                                       Random random,
                                                       Gravitational centerBody) {
        double inclinationMax = maxInclination;
        while (maxInclination > Math.PI/2){
            inclinationMax -= (Math.PI/2);
        }

        return new Orbit(
                random.nextDouble(
                        Double.min(Math.abs(minimumAURadius),Math.abs(maximumAURadius))*PhysicsConstants.AU,
                        Double.max(Math.abs(minimumAURadius),Math.abs(maximumAURadius))*PhysicsConstants.AU),
                random.nextDouble(0, maximumEccentricity - (int)maximumEccentricity),
                prograde ? random.nextDouble(0,inclinationMax)
                        : random.nextDouble(inclinationMax + Math.PI/2, Math.PI),
                random.nextDouble()*2*Math.PI,
                random.nextDouble()*2*Math.PI,
                random.nextDouble()*2*Math.PI,
                centerBody
        );
    }

