package com.kaymlyn.planeteater.simulation.celestial;

import com.kaymlyn.planeteater.simulation.physics.Orbit;
import com.kaymlyn.planeteater.simulation.physics.Vector3D;

/**
 * Contract for any object that participates in the n-body gravitational simulation.
 *
 * Any object with mass, position, and velocity belongs in the physics simulation,
 * regardless of whether it orbits a parent body, has thrusters, or is a megastructure.
 *
 * The OrbitalSystem Verlet integrator works over collections of PhysicsBody. This means
 * that satellites, spacecraft, stations, and future exotic constructs (ring worlds,
 * shepherded asteroids, large stations with their own satellites) all participate in
 * gravity without needing a shared class hierarchy beyond this interface.
 *
 * Hierarchy:
 *   PhysicsBody
 *   |-- Orbiter          (has a parent Gravitational, snapshotOrbit available)
 *       |-- Gravitational (massive enough to attract other bodies)
 *       |-- Satellite    (not massive enough to gravitationally matter)
 *   |-- Spacecraft       (has thrusters, itinerary, significant delta-V capability)
 *
 * Generated by Claude (Sonnet 4.5)
 */
public interface PhysicsBody {

    /**
     * Unique identifier for this body within the simulation.
     *
     * @return non-null, non-empty identifier
     */
    String getId();

    /**
     * Current position in the simulation coordinate frame (meters).
     *
     * @return position vector
     */
    Vector3D getPosition();

    /**
     * Current velocity in the simulation coordinate frame (m/s).
     *
     * @return velocity vector
     */
    Vector3D getVelocity();

    /**
     * Set position. Called by the Verlet integrator each step.
     *
     * @param position new position vector
     */
    void setPosition(Vector3D position);

    /**
     * Set velocity. Called by the Verlet integrator each step.
     *
     * @param velocity new velocity vector
     */
    void setVelocity(Vector3D velocity);

    /**
     * Current mass in kilograms. Used to calculate gravitational force.
     * May change over time (e.g. spacecraft consuming fuel).
     *
     * @return mass in kg, must be >= 0
     */
    double getMass();

    /**
     * Apply an acceleration over a time step and update position and velocity.
     * Implementations should use this as a hook for any per-step bookkeeping
     * beyond what the Verlet integrator handles directly.
     *
     * @param acceleration gravitational acceleration vector (m/s^2)
     * @param timeStep     duration of this integration step (seconds)
     */
    void update(Vector3D acceleration, double timeStep);

    default Vector3D getPosition(double tPlus) {
        return snapshotOrbit().stateAt(getSystem().getCurrentTime(),tPlus).position();
    }

    Orbit snapshotOrbit();

    OrbitalSystem getSystem();
}