package com.kaymlyn.planeteater.simulation.celestial.planetoid;

import com.kaymlyn.planeteater.simulation.celestial.BodyType;
import com.kaymlyn.planeteater.simulation.celestial.CelestialBody;
import com.kaymlyn.planeteater.simulation.celestial.OrbitalSystem;
import com.kaymlyn.planeteater.simulation.physics.PhysicsConstants;
import com.kaymlyn.planeteater.simulation.resources.Composition;
import com.kaymlyn.planeteater.simulation.resources.Material;
import com.kaymlyn.planeteater.simulation.physics.Vector3D;
import lombok.Getter;

/**
 * Represents a planet with differentiated layers
 * Unlike asteroids, planets have distinct core, mantle, and crust/atmosphere
 * 
 * Generated by Claude (Sonnet 4.5)
 */
@Getter
public class Planet extends CelestialBody implements Differentiated{

    @Getter
    private final CelestialBody parentBody;
    private final BodyType type;
    private final Composition coreComposition;
    private final Composition mantleComposition;
    private final Composition crustComposition;
    private final Composition atmosphereComposition;
    
    public Planet(String id, CelestialBody parentBody, OrbitalSystem system, Vector3D position, Vector3D velocity, BodyType type) {
        super(id, system, position, velocity);
        this.type = type;
        this.coreComposition = new Composition();
        this.mantleComposition = new Composition();
        this.crustComposition = new Composition();
        this.atmosphereComposition = new Composition();
        this.parentBody = parentBody;
    }
    
    /**
     * Override to calculate total mass from all layers
     */
    @Override
    protected double getAggregatedMass() {
        return coreComposition.getTotalMass() + 
               mantleComposition.getTotalMass() + 
               crustComposition.getTotalMass() + 
               atmosphereComposition.getTotalMass();
    }


    /**
     * For planets, radius should be set explicitly based on layer volumes
     */
    @Override
    public double getRadius() {
        // Sum volumes of all layers and calculate radius
        return Math.cbrt((3.0 * totalVolume()) / (4.0 * Math.PI));
    }

    @Override
    public double getDensity() {
        return coreComposition.getTotalMass()/getRadius();
    }

    @Override
    public double getVolume() {
        return coreComposition.getTotalVolume()
                + mantleComposition.getTotalVolume()
                + crustComposition.getTotalVolume()
                + getAtmosphereComposition().getTotalVolume();
    }
    /**
     * For planets, only the crust and atmosphere are accessible for mining
     * Deep mining could theoretically access mantle materials
     */
    @Override
    public boolean canMineCrust() {
        return crustComposition.getTotalMass() > 0;
    }

    @Override
    public boolean canHarvestAtmosphere() {
        return atmosphereComposition.getTotalMass() > 0;
    }

    /**
     * Mine from the crust (surface mining)
     */
    @Override
    public double mineCrustMaterial(Material material, double requestedMass) {
        if (!canMineCrust()) {
            return 0.0;
        }
        return crustComposition.removeMaterial(material, requestedMass);
    }

    /**
     * Extract from atmosphere (gas harvesting)
     */
    @Override
    public double harvestAtmosphere(Material material, double requestedMass) {
        if (!canHarvestAtmosphere()) {
            return 0.0;
        }
        return atmosphereComposition.removeMaterial(material, requestedMass);
    }

    /**d
     * Check if this satellite can have stable sub-satellites (moons of moons)
     * Generally requires Hill sphere radius >> sub-satellite radius
     */
    public boolean canHaveSubSatellites() {
        double hillRadius = calculateHillSphereRadius();
        // Need Hill sphere at least 10x the satellite's radius for stability
        return hillRadius > (10.0 * getRadius());
    }

    public boolean isTidallyLocked() {
        // Large moons close to their parent tend to be tidally locked
        // Simplified check: if Hill sphere ratio is small, likely locked
        double hillRadius = calculateHillSphereRadius();
        return hillRadius < (50.0 * getRadius());
    }

    /**
     * Gravitational pull at the surface
     * @return Small g for the planet in m*s^-2
     */
    public double getSurfaceGravity() {
        return PhysicsConstants.G * this.getMass()/Math.pow(getRadius(),2);
    }

    private double totalVolume() {
        return coreComposition.getTotalVolume() +
                mantleComposition.getTotalVolume() +
                crustComposition.getTotalVolume() +
                atmosphereComposition.getTotalVolume();
    }

    /**
     * Calculate Hill sphere radius - region where satellite can have stable sub-satellites
     * r_Hill = a * (m_satellite / (3 * m_parent))^(1/3)
     */
    public double calculateHillSphereRadius() {

        return this.getPosition().distanceTo(parentBody.getPosition()) * Math.pow(getMass() / (3.0 * parentBody.getMass()), 1.0/3.0);
    }
}