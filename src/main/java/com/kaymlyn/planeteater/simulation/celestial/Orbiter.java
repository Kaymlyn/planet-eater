package com.kaymlyn.planeteater.simulation.celestial;

import com.kaymlyn.planeteater.simulation.physics.Orbit;
import com.kaymlyn.planeteater.simulation.physics.Vector3D;

/**
 * Contract for objects that orbit a gravitational body.
 *
 * An Orbiter is a PhysicsBody that is gravitationally bound to a parent body.
 * Position and velocity are ground truth; orbital elements are derived on demand
 * via snapshotOrbit() and are only valid at the instant they are calculated.
 *
 * Orbiter does NOT imply the body is small or lacks thrusters. CentralMind
 * (an orbital station with docking capability) is an Orbiter. What distinguishes
 * an Orbiter from a plain PhysicsBody is the existence of a meaningful parentBody
 * reference and the ability to produce orbital elements at any instant.
 *
 * Spacecraft are NOT Orbiters. Spacecraft may be in orbit physically, but their
 * primary identity is as PhysicsBody objects with thruster capability. Their
 * relationship to a gravitational body is tracked via their SpacecraftState, not
 * via the Orbiter contract.
 *
 * Generated by Claude (Sonnet 4.5) - Refactored to extend PhysicsBody
 */
public interface Orbiter extends PhysicsBody {

    /**
     * The gravitational body this orbiter is primarily bound to.
     *
     * @return parent gravitational body, never null after placement
     */
    Gravitational getParentBody();

    /**
     * The OrbitalSystem this orbiter belongs to.
     *
     * @return the owning system
     */
    OrbitalSystem getSystem();

    /**
     * Set the parent gravitational body. Called during placement by OrbitalSystem.
     *
     * @param parentBody the gravitational body to orbit
     */
    void setParentBody(Gravitational parentBody);

    /**
     * Calculate orbital elements from current position and velocity.
     *
     * The result is only valid at this instant. In an n-body system, the actual
     * trajectory will diverge immediately due to perturbations from other bodies.
     * Use this for analysis and trajectory planning, not for position tracking.
     *
     * @return orbital elements at this instant
     */
    default Orbit snapshotOrbit() {
        return Orbit.fromState(getParentBody(), getPosition(), getVelocity());
    }

    /**
     * Predict position at a future simulation time using a 2-body approximation.
     *
     * Valid only for short prediction horizons in weakly-perturbed systems.
     * For position tracking, run the simulation forward instead.
     *
     * @param tPlus absolute simulation time to predict for
     * @return predicted position at tPlus
     */
    default Vector3D getPosition(double tPlus) {
        return snapshotOrbit().stateAt(getSystem().getCurrentTime(), tPlus).position();
    }
}