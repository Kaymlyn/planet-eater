package com.kaymlyn.planeteater.rendering;

/**
 * Controls how celestial object and spacecraft pixel sizes are computed
 * when rendering into a view that may differ in scale from the original
 * single-view 1280x720 baseline.
 *
 * CONSTANT   - All sizes remain at their configured pixel values regardless
 *              of view dimensions. A 3-pixel planet stays 3 pixels at any
 *              view resolution. May feel cramped in smaller views.
 *
 * PROPORTIONAL - Sizes are multiplied by the ratio of the view's minor
 *              dimension to the baseline minor dimension (720 pixels).
 *              A 3-pixel planet at baseline becomes 2 pixels at 540-pixel
 *              height. Minimum 1 pixel is enforced.
 *
 * SMART      - Large bodies (above LARGE_BODY_THRESHOLD) are scaled
 *              proportionally; small bodies and spacecraft are held at
 *              minimum 1 pixel. Preserves visibility of major bodies
 *              while avoiding sub-pixel rendering of minor objects.
 *
 * Generated by Claude (Sonnet 4.5)
 */
public enum ObjectSizeStrategy {
    CONSTANT,
    PROPORTIONAL,
    SMART
}