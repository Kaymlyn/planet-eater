    /**
     * Render labels for non-asteroid orbiters
     */
    private void renderOrbiterLabels(Graphics2D g2d, RotationMatrix rotation, double canvasScale) {
        for(Orbiter orbiter : system.getOrbiters().values()) {
            String id = orbiter.getId();

            // Skip if this object shouldn't have a label (asteroids)
            if(!shouldLabelCache.get(id)) {
                continue;
            }

            // Transform position (same calculation as rendering)
            Vector3D position = orbiter.getPosition();
            Vector3D rotated = rotation.transform(position);

            int screenX = (int)(rotated.getX() / canvasScale * adjustedAU + centerX);
            int screenY = (int)(rotated.getY() / canvasScale * adjustedAU + centerY);

            // Draw label offset from object
            g2d.drawString(id, screenX + 3, screenY);
        }
    }

    /**
     * Render all orbiters - batch processing
     */
    private void renderAllOrbiters(int[] pixels, RotationMatrix rotation, double canvasScale) {
        for(Orbiter orbiter : system.getOrbiters().values()) {
            String id = orbiter.getId();

            // Transform position (single matrix multiply)
            Vector3D position = orbiter.getPosition();
            Vector3D rotated = rotation.transform(position);

            int screenX = (int)(rotated.getX() / canvasScale * adjustedAU + centerX);
            int screenY = (int)(rotated.getY() / canvasScale * adjustedAU + centerY);

            // Use cached properties
            Color color = colorCache.get(id);
            int size = sizeCache.get(id);

            drawFilledSquare(pixels, screenX, screenY, size, color.getRGB());
        }
    }

    /**
     * Render all spacecraft (in transit only; docked are omitted to avoid label clutter).
     */
    private void renderAllSpacecraft(int[] pixels, RotationMatrix rotation, double canvasScale) {
        for (Spacecraft spacecraft : system.getSpacecraftInTransit().values()) {
            if (spacecraft.getState() == Spacecraft.SpacecraftState.DOCKED) {
                continue;
            }

            Vector3D position = getCurrentSpacecraftPosition(spacecraft);
            Vector3D rotated = rotation.transform(position);

            int screenX = (int)(rotated.getX() / canvasScale * adjustedAU + centerX);
            int screenY = (int)(rotated.getY() / canvasScale * adjustedAU + centerY);

            drawFilledSquare(pixels, screenX, screenY, SPACECRAFT_SIZE, COLOR_SPACECRAFT.getRGB());
        }
    }

    /**
     * Render labels for spacecraft with state info
     */
    private void renderSpacecraftLabels(Graphics2D g2d, RotationMatrix rotation, double canvasScale) {
        for (Spacecraft spacecraft : system.getSpacecraftInTransit().values()) {
            if (spacecraft.getState() == Spacecraft.SpacecraftState.DOCKED) {
                continue;
            }

            Vector3D position = getCurrentSpacecraftPosition(spacecraft);
            Vector3D rotated = rotation.transform(position);

            int screenX = (int)(rotated.getX() / canvasScale * adjustedAU + centerX);
            int screenY = (int)(rotated.getY() / canvasScale * adjustedAU + centerY);

            // Draw label with state, offset below the spacecraft
            String label = spacecraft.getId() + " " + spacecraft.getState();
            g2d.drawString(label, screenX, screenY + 10);
        }
    }

    /**
     * Get spacecraft position for rendering. When in transit with telemetry, uses the
     * current simulation time to pick the correct telemetry sample so the craft is
     * drawn at the position that matches the current time (avoids drift vs orbiters).
     */
    private Vector3D getCurrentSpacecraftPosition(Spacecraft spacecraft) {
        // Use new time-based API - simpler and more robust
        double currentTime = system.getCurrentTime();
        return spacecraft.getPositionAtTime(currentTime);
    }

    /**
     * Draw filled circle directly to pixel buffer - FAST
     */
    private void drawFilledCircle(int[] pixels, int cx, int cy, int radius, int rgb) {
        int r2 = radius * radius;
        for(int dy = -radius; dy <= radius; dy++) {
            for(int dx = -radius; dx <= radius; dx++) {
                if(dx*dx + dy*dy <= r2) {
                    int x = cx + dx;
                    int y = cy + dy;
                    if(x >= 0 && x < width && y >= 0 && y < height) {
                        pixels[y * width + x] = rgb;
                    }
                }
            }
        }
    }

    /**
     * Draw filled square directly to pixel buffer - FAST
     */
    private void drawFilledSquare(int[] pixels, int x, int y, int size, int rgb) {
        for(int dy = 0; dy < size; dy++) {
            for(int dx = 0; dx < size; dx++) {
                int px = x + dx;
                int py = y + dy;
                if(px >= 0 && px < width && py >= 0 && py < height) {
                    pixels[py * width + px] = rgb;
                }
            }
        }
    }

    /**
     * Pre-computed rotation matrix for camera transformation
     * Avoids 3 separate rotateAroundVector calls per object
     */
    private static class RotationMatrix {
        private final double[][] matrix = new double[3][3];

        public RotationMatrix(Vector3D eulerAngles) {
            // Build composite rotation matrix: Rz * Ry * Rx
            double cx = Math.cos(eulerAngles.getX());
            double sx = Math.sin(eulerAngles.getX());
            double cy = Math.cos(eulerAngles.getY());
            double sy = Math.sin(eulerAngles.getY());
            double cz = Math.cos(eulerAngles.getZ());
            double sz = Math.sin(eulerAngles.getZ());

            // Combined rotation matrix
            matrix[0][0] = cy * cz;
            matrix[0][1] = -cy * sz;
            matrix[0][2] = sy;

            matrix[1][0] = sx * sy * cz + cx * sz;
            matrix[1][1] = -sx * sy * sz + cx * cz;
            matrix[1][2] = -sx * cy;

            matrix[2][0] = -cx * sy * cz + sx * sz;
            matrix[2][1] = cx * sy * sz + sx * cz;
            matrix[2][2] = cx * cy;
        }

        public Vector3D transform(Vector3D v) {
            double x = matrix[0][0] * v.getX() + matrix[0][1] * v.getY() + matrix[0][2] * v.getZ();
            double y = matrix[1][0] * v.getX() + matrix[1][1] * v.getY() + matrix[1][2] * v.getZ();
            double z = matrix[2][0] * v.getX() + matrix[2][1] * v.getY() + matrix[2][2] * v.getZ();
            return new Vector3D(x, y, z);
        }
    }
