package com.kaymlyn.planeteater.rendering;

import com.kaymlyn.planeteater.simulation.physics.Vector3D;

/**
 * Named camera angle presets for use as the angled (aesthetic) view in
 * multi-view rendering. Each preset encodes Euler angles (x, y, z) in
 * radians that are passed directly to RotationMatrix.
 *
 * The rotation convention matches OrbitalSystemRendererOptimized: Rz * Ry * Rx
 * applied to world-space positions. A zero vector produces a top-down view
 * looking down the Z axis.
 *
 * Preset descriptions assume the ecliptic plane lies in XY and Z is
 * perpendicular (north pole up):
 *
 *   ISOMETRIC_SHALLOW  - 30 deg tilt, 30 deg azimuth. Gentle depth, broad view.
 *   ISOMETRIC_STANDARD - 45 deg tilt, 30 deg azimuth. Classic isometric feel.
 *   ISOMETRIC_STEEP    - 60 deg tilt, 45 deg azimuth. Strong depth emphasis.
 *   THREE_QUARTER      - 45 deg tilt, 45 deg azimuth with 22.5 deg roll.
 *                        Balanced perspective showing all three axes clearly.
 *   OBLIQUE_HIGH       - 60 deg tilt, 30 deg azimuth. High vantage, clear Z spread.
 *   OBLIQUE_LOW        - 20 deg tilt, 45 deg azimuth. Near-edge-on, shows
 *                        orbital inclinations clearly without full edge-on.
 *
 * Generated by Claude (Sonnet 4.5)
 */
public enum AngledViewPreset {

    ISOMETRIC_SHALLOW(Math.PI / 6.0, Math.PI / 6.0, 0.0),
    ISOMETRIC_STANDARD(Math.PI / 4.0, Math.PI / 6.0, 0.0),
    ISOMETRIC_STEEP(Math.PI / 3.0, Math.PI / 4.0, 0.0),
    THREE_QUARTER(Math.PI / 4.0, Math.PI / 4.0, Math.PI / 8.0),
    OBLIQUE_HIGH(Math.PI / 3.0, Math.PI / 6.0, 0.0),
    OBLIQUE_LOW(Math.PI / 9.0, Math.PI / 4.0, 0.0);

    private final double xRotation;
    private final double yRotation;
    private final double zRotation;

    AngledViewPreset(double xRotation, double yRotation, double zRotation) {
        this.xRotation = xRotation;
        this.yRotation = yRotation;
        this.zRotation = zRotation;
    }

    /**
     * Return the rotation as a Vector3D suitable for passing to RotationMatrix
     * or the ViewConfig constructor.
     *
     * @return rotation Euler angles in radians
     */
    public Vector3D toRotation() {
        return new Vector3D(xRotation, yRotation, zRotation);
    }
}