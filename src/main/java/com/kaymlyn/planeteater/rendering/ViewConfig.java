package com.kaymlyn.planeteater.rendering;

import com.kaymlyn.planeteater.simulation.physics.Vector3D;

/**
 * Complete configuration for a single rendered view panel.
 *
 * A ViewConfig specifies everything the renderer needs to produce one panel
 * of a multi-view composite or one full single-view frame:
 *
 *   rotation           - Camera orientation as Euler angles (radians).
 *                        Passed directly to RotationMatrix. Zero produces
 *                        a top-down view looking down the Z axis.
 *
 *   gridConfig         - Reference frame overlay (axes and ecliptic grid).
 *
 *   labelConfig        - Per-object-type label visibility.
 *
 *   objectSizeStrategy - How pixel sizes scale relative to view dimensions.
 *
 *   showTimestamp      - Whether to render the simulation time in the corner.
 *
 *   viewTitle          - Short string drawn in the corner to identify the view
 *                        (e.g. "Top-Down", "Edge XZ"). Empty string suppresses.
 *
 * Static factory methods cover the four canonical views used in multi-view layout.
 *
 * Generated by Claude (Sonnet 4.5)
 */
public class ViewConfig {

    private final Vector3D rotation;
    private final GridConfig gridConfig;
    private final LabelConfig labelConfig;
    private final ObjectSizeStrategy objectSizeStrategy;
    private final boolean showTimestamp;
    private final String viewTitle;

    private ViewConfig(Builder builder) {
        this.rotation = builder.rotation;
        this.gridConfig = builder.gridConfig;
        this.labelConfig = builder.labelConfig;
        this.objectSizeStrategy = builder.objectSizeStrategy;
        this.showTimestamp = builder.showTimestamp;
        this.viewTitle = builder.viewTitle;
    }

    public Vector3D getRotation() { return rotation; }
    public GridConfig getGridConfig() { return gridConfig; }
    public LabelConfig getLabelConfig() { return labelConfig; }
    public ObjectSizeStrategy getObjectSizeStrategy() { return objectSizeStrategy; }
    public boolean isShowTimestamp() { return showTimestamp; }
    public String getViewTitle() { return viewTitle; }

    public static Builder builder() {
        return new Builder();
    }

    // ==================== CANONICAL VIEW FACTORIES ====================

    /**
     * Top-down view: camera looks straight down the Z axis.
     * Full grid, all labels, timestamp.
     */
    public static ViewConfig topDown() {
        return builder()
                .rotation(new Vector3D(0.0, 0.0, 0.0))
                .gridConfig(GridConfig.full())
                .labelConfig(LabelConfig.allEnabled())
                .objectSizeStrategy(ObjectSizeStrategy.PROPORTIONAL)
                .showTimestamp(true)
                .viewTitle("Top-Down")
                .build();
    }

    /**
     * Edge-on XZ view: 90-degree tilt around X axis, ecliptic seen edge-on.
     * Axes only, major body labels.
     */
    public static ViewConfig edgeOnXZ() {
        return builder()
                .rotation(new Vector3D(Math.PI / 2.0, 0.0, 0.0))
                .gridConfig(GridConfig.axesOnly())
                .labelConfig(LabelConfig.majorBodiesOnly())
                .objectSizeStrategy(ObjectSizeStrategy.PROPORTIONAL)
                .showTimestamp(false)
                .viewTitle("Edge-On XZ")
                .build();
    }

    /**
     * Edge-on YZ view: 90-degree rotation around Z axis, orthogonal to edgeOnXZ.
     * Axes only, major body labels.
     */
    public static ViewConfig edgeOnYZ() {
        return builder()
                .rotation(new Vector3D(0.0, 0.0, Math.PI / 2.0))
                .gridConfig(GridConfig.axesOnly())
                .labelConfig(LabelConfig.majorBodiesOnly())
                .objectSizeStrategy(ObjectSizeStrategy.PROPORTIONAL)
                .showTimestamp(false)
                .viewTitle("Edge-On YZ")
                .build();
    }

    /**
     * Angled aesthetic view using a named preset.
     * Full grid, all labels.
     */
    public static ViewConfig angled(AngledViewPreset preset) {
        return builder()
                .rotation(preset.toRotation())
                .gridConfig(GridConfig.full())
                .labelConfig(LabelConfig.allEnabled())
                .objectSizeStrategy(ObjectSizeStrategy.PROPORTIONAL)
                .showTimestamp(false)
                .viewTitle("Angled (" + preset.name() + ")")
                .build();
    }

    /**
     * Convenience factory for the default four-view layout using the standard
     * ISOMETRIC_STANDARD preset for the angled view.
     */
    public static ViewConfig[] defaultFourViews() {
        return new ViewConfig[] {
                topDown(),
                edgeOnXZ(),
                edgeOnYZ(),
                angled(AngledViewPreset.ISOMETRIC_STANDARD)
        };
    }

    public static class Builder {
        private Vector3D rotation = new Vector3D(0.0, 0.0, 0.0);
        private GridConfig gridConfig = GridConfig.disabled();
        private LabelConfig labelConfig = LabelConfig.allEnabled();
        private ObjectSizeStrategy objectSizeStrategy = ObjectSizeStrategy.PROPORTIONAL;
        private boolean showTimestamp = false;
        private String viewTitle = "";

        public Builder rotation(Vector3D rotation) { this.rotation = rotation; return this; }
        public Builder gridConfig(GridConfig gridConfig) { this.gridConfig = gridConfig; return this; }
        public Builder labelConfig(LabelConfig labelConfig) { this.labelConfig = labelConfig; return this; }
        public Builder objectSizeStrategy(ObjectSizeStrategy objectSizeStrategy) {
            this.objectSizeStrategy = objectSizeStrategy; return this;
        }
        public Builder showTimestamp(boolean showTimestamp) { this.showTimestamp = showTimestamp; return this; }
        public Builder viewTitle(String viewTitle) { this.viewTitle = viewTitle; return this; }

        public ViewConfig build() {
            return new ViewConfig(this);
        }
    }
}